//! Constant-rate, encrypted links between consecutive servers ("per-hop shaping").
//!
//! The client's link to the first hop is the WireGuard + DAITA carrier, which already
//! runs the constant-rate stream. Behind it, a relay forwards the next layer's QUIC
//! packets to the next hop. Sent raw, those packets showed every transfer on the wire:
//! measured on v0.7.0, the link into the exit went from 0.5 packets/s idle (small QUIC
//! control packets) to thousands per second during a download.
//!
//! A paced link closes that gap with the same invariant as the carrier:
//!
//! - **Cells.** Every forwarded packet travels in a fixed-size cell
//!   (`[len][packet][zero padding]`), encrypted with AES-256-GCM, so a real cell and an
//!   empty (dummy) cell are the same size and both look like random bytes.
//! - **Clock.** The sender emits `slots` cells every `clock` on a drift-free grid
//!   ([`Pace`], the chain's signed [`RateClass`]): a queued packet if there is one, a
//!   dummy otherwise. A full queue drops (the transport above sees a bottleneck); it
//!   never bursts outside the clock.
//! - **Keys.** Each link has its own 32-byte pre-shared key, generated by the operator at
//!   `avpn init` and sealed to each device's hybrid post-quantum KEM key, like the
//!   WireGuard PSK. Every sender session draws a random 16-byte session id and derives
//!   its key as HKDF-SHA256(psk, salt = id, info = direction), so a restarted sender
//!   never reuses a nonce, and a cell reflected back to its sender fails to open.
//! - **No amplification.** The receiving end ([`ingress`]) answers a peer only with
//!   credit earned from that peer's authenticated cells, at most `slots` per tick. A
//!   spoofed or unauthenticated packet earns nothing, so a paced server is never a
//!   reflector. Because the relay's stream is constant, the reply stream is too.
use crate::daita::RateClass;
use anyhow::{Context, Result, bail, ensure};
use aws_lc_rs::{
    aead::{AES_256_GCM, Aad, LessSafeKey, NONCE_LEN, Nonce, UnboundKey},
    hkdf::{HKDF_SHA256, Salt},
    rand::{SecureRandom, SystemRandom},
};
use bytes::Bytes;
use std::{
    collections::HashMap,
    net::SocketAddr,
    sync::{
        Arc,
        atomic::{AtomicU64, Ordering},
    },
    time::{Duration, Instant},
};
