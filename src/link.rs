/// Random per-sender-session identifier carried in clear on every cell.
pub const SESSION_ID: usize = 16;
const COUNTER: usize = 8;
const TAG: usize = 16;
/// Bytes a link adds around a cell: session id, counter and AEAD tag.
pub const OVERHEAD: usize = SESSION_ID + COUNTER + TAG;
/// How long a receiving end keeps a silent peer before forgetting it. A live sender
/// is never silent: its clock sends a cell every tick.
pub const PEER_IDLE: Duration = Duration::from_secs(15);
/// Most reply credit a peer may hold, in ticks of its clock: enough to ride out
/// jitter, never enough to burst (at most `slots` cells leave per tick regardless).
const CREDIT_TICKS: u64 = 500;
/// A sender session lasts at most this long before the next key exchange.
pub const REKEY: Duration = Duration::from_secs(120);
/// How long a superseded session still opens (cells already in flight), before its key
/// is erased.
const RETIRE_GRACE: Duration = Duration::from_secs(5);
/// Length-field flag: the cell carries a handshake message, not a packet.
const CONTROL: u16 = 0x8000;
/// Handshake message kinds.
/// v1 (OFFER/ANSWER): X25519 + ML-KEM-768 + HKDF-SHA256 (legacy compatibility).
/// v2 (OFFER_V2/ANSWER_V2): X25519 + ML-KEM-1024 + dual HKDF-SHA-512 XOR HKDF-SHA3-512.
const OFFER: u8 = 1;
const ANSWER: u8 = 2;
const OFFER_V2: u8 = 3;
const ANSWER_V2: u8 = 4;
/// Bytes before a handshake fragment: kind, part, parts.
const FRAGMENT_HEADER: usize = 3;
/// How often an unanswered offer is sent again (cells are unreliable).
const OFFER_EVERY: Duration = Duration::from_millis(250);

/// Which way a cell travels: forward is away from the client (relay towards its next
/// hop), reverse is back towards it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Dir {
    /// Relay to its next hop.
    Forward,
    /// The next hop back to the relay.
    Reverse,
}

impl Dir {
    fn info(self) -> &'static [u8] {
        match self {
            Dir::Forward => b"cypherpunk-vpn/link/v1/forward",
            Dir::Reverse => b"cypherpunk-vpn/link/v1/reverse",
        }
    }
}

/// The clock of a paced link: `slots` cells every `clock`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Pace {
    /// Time between ticks.
    pub clock: Duration,
    /// Cells per tick.
    pub slots: u32,
}

impl Pace {
    /// The clock of a rate class (the same as the carrier's on every hop).
    pub fn of(rate: RateClass) -> Self {
        Pace {
            clock: Duration::from_micros(rate.clock_us()),
            slots: rate.slots(),
        }
    }
    /// Cells per second.
    pub fn per_second(self) -> f64 {
        self.slots as f64 / self.clock.as_secs_f64()
    }
    /// The send queue: about 100 ms of cells, at least 128.
    pub fn queue(self) -> usize {
        ((self.per_second() / 10.0) as usize).clamp(128, 4096)
    }
}

fn derive(psk: &[u8; 32], id: &[u8; SESSION_ID], dir: Dir) -> Result<LessSafeKey> {
    let mut key = [0u8; 32];
    Salt::new(HKDF_SHA256, id)
        .extract(psk)
        .expand(&[dir.info()], HKDF_SHA256)
        .map_err(|_| anyhow::anyhow!("link key derivation failed"))?
        .fill(&mut key)
        .map_err(|_| anyhow::anyhow!("link key derivation failed"))?;
    let unbound =
        UnboundKey::new(&AES_256_GCM, &key).map_err(|_| anyhow::anyhow!("bad link key"))?;
    Ok(LessSafeKey::new(unbound))
}

fn nonce(counter: u64) -> Nonce {
    let mut n = [0u8; NONCE_LEN];
    n[NONCE_LEN - 8..].copy_from_slice(&counter.to_be_bytes());
    Nonce::assume_unique_for_key(n)
}

/// The sending half of one link session: a fresh random session id and key.
pub struct Sealer {
    id: [u8; SESSION_ID],
    key: LessSafeKey,
    counter: u64,
}

impl Sealer {
    /// A new sender session on `psk` in direction `dir`.
    pub fn new(psk: &[u8; 32], dir: Dir) -> Result<Self> {
        let mut id = [0u8; SESSION_ID];
        SystemRandom::new()
            .fill(&mut id)
            .map_err(|_| anyhow::anyhow!("no randomness"))?;
        Ok(Sealer {
            key: derive(psk, &id, dir)?,
            id,
            counter: 0,
        })
    }
    /// A sender session under a key from the handshake.
    fn keyed(id: [u8; SESSION_ID], key: &[u8; 32]) -> Result<Self> {
        let unbound =
            UnboundKey::new(&AES_256_GCM, key).map_err(|_| anyhow::anyhow!("bad link key"))?;
        Ok(Sealer {
            id,
            key: LessSafeKey::new(unbound),
            counter: 0,
        })
    }
    /// One wire cell carrying `payload` (empty for a dummy), framed to `cell` bytes.
    pub fn seal(&mut self, payload: &[u8], cell: usize) -> Result<Vec<u8>> {
        self.seal_framed(payload, cell, false)
    }
    /// One wire cell carrying a handshake fragment.
    fn seal_control(&mut self, msg: &[u8], cell: usize) -> Result<Vec<u8>> {
        self.seal_framed(msg, cell, true)
    }
    fn seal_framed(&mut self, payload: &[u8], cell: usize, control: bool) -> Result<Vec<u8>> {
        ensure!(
            payload.len() + 2 <= cell,
            "packet larger than the link cell"
        );
        ensure!(self.counter < u64::MAX, "link session exhausted");
        let counter = self.counter;
        self.counter += 1;
        let mut out = Vec::with_capacity(OVERHEAD + cell);
        out.extend_from_slice(&self.id);
        out.extend_from_slice(&counter.to_be_bytes());
        let header = out.clone();
        let mut body = vec![0u8; cell];
        let len = payload.len() as u16 | if control { CONTROL } else { 0 };
        body[..2].copy_from_slice(&len.to_be_bytes());
        body[2..2 + payload.len()].copy_from_slice(payload);
        self.key
            .seal_in_place_append_tag(nonce(counter), Aad::from(&header[..]), &mut body)
            .map_err(|_| anyhow::anyhow!("seal failed"))?;
        out.extend_from_slice(&body);
        Ok(out)
    }
}

/// One sender session an [`Opener`] accepts.
struct Session {
    id: [u8; SESSION_ID],
    index: usize,
    key: LessSafeKey,
    window: Window,
    /// Keyed by a handshake (true) or derived from the PSK alone (false).
    rekeyed: bool,
    /// Superseded: erased at this time.
    expires: Option<Instant>,
}

/// What one opened cell carried.
struct Opened {
    /// Which pre-shared key the session belongs to.
    index: usize,
    id: [u8; SESSION_ID],
    payload: Vec<u8>,
    control: bool,
    rekeyed: bool,
}

/// The receiving half of a link: the keys it accepts, and the sessions seen on them.
pub struct Opener {
    psks: Vec<[u8; 32]>,
    dir: Dir,
    /// Live sender sessions. Bounded.
    sessions: Vec<Session>,
    /// Superseded session ids, never admitted again (bounded).
    retired: std::collections::VecDeque<[u8; SESSION_ID]>,
}

impl Opener {
    /// Accept cells in direction `dir` under any of `psks`.
    pub fn new(psks: Vec<[u8; 32]>, dir: Dir) -> Self {
        Opener {
            psks,
            dir,
            sessions: Vec::new(),
            retired: std::collections::VecDeque::new(),
        }
    }
    /// Open one wire cell of `cell` bytes. `None`: not authentic, replayed, malformed or a
    /// handshake message. `Some((psk index, payload))`: the payload is empty for a dummy.
    pub fn open(&mut self, wire: &[u8], cell: usize) -> Option<(usize, Vec<u8>)> {
        let o = self.open_cell(wire, cell)?;
        (!o.control).then_some((o.index, o.payload))
    }
    /// Accept the session `id` under a handshake key; `supersede`: the session it replaces
    /// (kept [`RETIRE_GRACE`] for cells in flight, then erased), or every other session.
    fn add_session(
        &mut self,
        id: [u8; SESSION_ID],
        index: usize,
        key: &[u8; 32],
        supersede: Option<[u8; SESSION_ID]>,
    ) {
        let Ok(unbound) = UnboundKey::new(&AES_256_GCM, key) else {
            return;
        };
        let end = Instant::now() + RETIRE_GRACE;
        for s in &mut self.sessions {
            if s.id != id && supersede.is_none_or(|old| old == s.id) && s.expires.is_none() {
                s.expires = Some(end);
            }
        }
        self.sessions.retain(|s| s.id != id);
        if self.sessions.len() >= 8 {
            self.retire(0);
        }
        self.sessions.push(Session {
            id,
            index,
            key: LessSafeKey::new(unbound),
            window: Window::default(),
            rekeyed: true,
            expires: None,
        });
    }
    fn retire(&mut self, pos: usize) {
        let s = self.sessions.remove(pos);
        if self.retired.len() >= 64 {
            self.retired.pop_front();
        }
        self.retired.push_back(s.id);
    }
    fn open_cell(&mut self, wire: &[u8], cell: usize) -> Option<Opened> {
        if wire.len() != OVERHEAD + cell {
            return None;
        }
        let now = Instant::now();
        while let Some(pos) = self
            .sessions
            .iter()
            .position(|s| s.expires.is_some_and(|e| e <= now))
        {
            self.retire(pos);
        }
        let id: [u8; SESSION_ID] = wire[..SESSION_ID].try_into().ok()?;
        let counter = u64::from_be_bytes(wire[SESSION_ID..SESSION_ID + COUNTER].try_into().ok()?);
        let header = &wire[..SESSION_ID + COUNTER];
        let attempt = |key: &LessSafeKey| {
            let mut body = wire[SESSION_ID + COUNTER..].to_vec();
            let plain = key
                .open_in_place(nonce(counter), Aad::from(header), &mut body)
                .ok()?;
            let field = u16::from_be_bytes([plain[0], plain[1]]);
            let len = (field & !CONTROL) as usize;
            (2 + len <= plain.len()).then(|| (plain[2..2 + len].to_vec(), field & CONTROL != 0))
        };
        if let Some(pos) = self.sessions.iter().position(|s| s.id == id) {
            let (payload, control) = attempt(&self.sessions[pos].key)?;
            let s = &mut self.sessions[pos];
            // Only an authentic cell may advance the window.
            if !s.window.accept(counter) {
                return None;
            }
            return Some(Opened {
                index: s.index,
                id,
                payload,
                control,
                rekeyed: s.rekeyed,
            });
        }
        if self.retired.contains(&id) {
            return None;
        }
        for (index, psk) in self.psks.iter().enumerate() {
            let Ok(key) = derive(psk, &id, self.dir) else {
                continue;
            };
            if let Some((payload, control)) = attempt(&key) {
                let mut window = Window::default();
                window.accept(counter);
                // A restarted sender opens a new session; keep the few most recent.
                if self.sessions.len() >= 8 {
                    self.retire(0);
                }
                self.sessions.push(Session {
                    id,
                    index,
                    key,
                    window,
                    rekeyed: false,
                    expires: None,
                });
                return Some(Opened {
                    index,
                    id,
                    payload,
                    control,
                    rekeyed: false,
                });
            }
        }
        None
    }
}

/// A handshake's next-session keys: (forward, reverse).
type Keys = ([u8; 32], [u8; 32]);
/// The last offer a next hop answered: session id, the answer, and the reply key it holds
/// until the sender switches.
type Answered = (
    [u8; SESSION_ID],
    Vec<u8>,
    Option<zeroize::Zeroizing<[u8; 32]>>,
);

/// The handshake's next-session keys: forward and reverse, from the PSK, both ephemeral
/// shared secrets and a hash of the exchange (so neither message can be swapped).
fn session_keys(psk: &[u8; 32], offer: &[u8], answer: &[u8], secrets: &[u8]) -> Result<Keys> {
    use sha2::{Digest, Sha256};
    let mut h = Sha256::new();
    h.update(b"cypherpunk-vpn/link/v2/handshake");
    h.update((offer.len() as u32).to_be_bytes());
    h.update(offer);
    h.update(answer);
    let th = h.finalize();
    let prk = Salt::new(HKDF_SHA256, psk).extract(secrets);
    let mut keys = ([0u8; 32], [0u8; 32]);
    for (dir, out) in [(Dir::Forward, &mut keys.0), (Dir::Reverse, &mut keys.1)] {
        prk.expand(&[b"cypherpunk-vpn/link/v2/", dir.info(), &th], HKDF_SHA256)
            .map_err(|_| anyhow::anyhow!("link key derivation failed"))?
            .fill(out)
            .map_err(|_| anyhow::anyhow!("link key derivation failed"))?;
    }
    Ok(keys)
}

/// RFC 5869 HKDF-Extract + single-block HKDF-Expand with HMAC-SHA-512.
fn hkdf_sha512_32(
    salt: &[u8],
    ikm: &[u8],
    info_parts: &[&[u8]],
) -> Result<zeroize::Zeroizing<[u8; 32]>> {
    use hmac::{Hmac, Mac};
    type H = Hmac<sha2::Sha512>;
    let mut extract = <H as Mac>::new_from_slice(salt).map_err(|_| anyhow::anyhow!("hkdf salt"))?;
    extract.update(ikm);
    let mut prk = zeroize::Zeroizing::new([0u8; 64]);
    prk.copy_from_slice(&extract.finalize().into_bytes());
    let mut expand =
        <H as Mac>::new_from_slice(&prk[..]).map_err(|_| anyhow::anyhow!("hkdf prk"))?;
    for part in info_parts {
        expand.update(part);
    }
    expand.update(&[1u8]);
    let mut block = zeroize::Zeroizing::new([0u8; 64]);
    block.copy_from_slice(&expand.finalize().into_bytes());
    let mut out = zeroize::Zeroizing::new([0u8; 32]);
    out.copy_from_slice(&block[..32]);
    Ok(out)
}

/// RFC 5869 HKDF-Extract + single-block HKDF-Expand with HMAC-SHA3-512 (Keccak sponge).
fn hkdf_sha3_512_32(
    salt: &[u8],
    ikm: &[u8],
    info_parts: &[&[u8]],
) -> Result<zeroize::Zeroizing<[u8; 32]>> {
    use hmac::{Hmac, Mac};
    type H = Hmac<sha3::Sha3_512>;
    let mut extract = <H as Mac>::new_from_slice(salt).map_err(|_| anyhow::anyhow!("hkdf salt"))?;
    extract.update(ikm);
    let mut prk = zeroize::Zeroizing::new([0u8; 64]);
    prk.copy_from_slice(&extract.finalize().into_bytes());
    let mut expand =
        <H as Mac>::new_from_slice(&prk[..]).map_err(|_| anyhow::anyhow!("hkdf prk"))?;
    for part in info_parts {
        expand.update(part);
    }
    expand.update(&[1u8]);
    let mut block = zeroize::Zeroizing::new([0u8; 64]);
    block.copy_from_slice(&expand.finalize().into_bytes());
    let mut out = zeroize::Zeroizing::new([0u8; 32]);
    out.copy_from_slice(&block[..32]);
    Ok(out)
}

/// Dual-PRF KDF combiner: HKDF-SHA-512 XOR HKDF-SHA3-512.
/// Preserves key confidentiality as long as either Merkle-Damgård SHA-512 OR Keccak SHA3-512
/// remains a secure PRF.
fn dual_hkdf_expand_32(
    salt: &[u8],
    ikm: &[u8],
    info_parts: &[&[u8]],
    out: &mut [u8; 32],
) -> Result<()> {
    let leg_sha2 = hkdf_sha512_32(salt, ikm, info_parts)?;
    let leg_sha3 = hkdf_sha3_512_32(salt, ikm, info_parts)?;
    for i in 0..32 {
        out[i] = leg_sha2[i] ^ leg_sha3[i];
    }
    Ok(())
}

/// Link v2 next-session keys: dual transcript hash (SHA-512 || SHA3-512) fed into
/// dual-PRF HKDF-SHA-512 XOR HKDF-SHA3-512 over PSK + X25519 + ML-KEM-1024 shared secrets.
fn session_keys_v2(psk: &[u8; 32], offer: &[u8], answer: &[u8], secrets: &[u8]) -> Result<Keys> {
    use sha2::Digest;
    let mut h2 = sha2::Sha512::new();
    h2.update(b"cypherpunk-vpn/link/v3/handshake");
    h2.update((offer.len() as u32).to_be_bytes());
    h2.update(offer);
    h2.update(answer);
    let d2 = h2.finalize();

    let mut h3 = sha3::Sha3_512::new();
    h3.update(b"cypherpunk-vpn/link/v3/handshake");
    h3.update((offer.len() as u32).to_be_bytes());
    h3.update(offer);
    h3.update(answer);
    let d3 = h3.finalize();

    let mut th = [0u8; 128];
    th[..64].copy_from_slice(&d2);
    th[64..].copy_from_slice(&d3);

    let mut keys = ([0u8; 32], [0u8; 32]);
    for (dir, out) in [(Dir::Forward, &mut keys.0), (Dir::Reverse, &mut keys.1)] {
        dual_hkdf_expand_32(
            psk,
            secrets,
            &[b"cypherpunk-vpn/link/v3/", dir.info(), &th],
            out,
        )?;
    }
    Ok(keys)
}

/// Link v2 initiator: ephemeral X25519 + NIST Level-5 ML-KEM-1024 + dual-PRF KDF.
struct InitiatorV2 {
    next: [u8; SESSION_ID],
    x25519: aws_lc_rs::agreement::EphemeralPrivateKey,
    mlkem: aws_lc_rs::kem::DecapsulationKey,
    offer: Vec<u8>,
}

impl InitiatorV2 {
    fn new() -> Result<Self> {
        use aws_lc_rs::{agreement, kem};
        let rng = SystemRandom::new();
        let mut next = [0u8; SESSION_ID];
        rng.fill(&mut next)
            .map_err(|_| anyhow::anyhow!("no randomness"))?;
        let x25519 = agreement::EphemeralPrivateKey::generate(&agreement::X25519, &rng)
            .map_err(|_| anyhow::anyhow!("x25519 keygen"))?;
        let mlkem = kem::DecapsulationKey::generate(&kem::ML_KEM_1024)
            .map_err(|_| anyhow::anyhow!("ml-kem-1024 keygen"))?;
        let mut offer = next.to_vec();
        offer.extend_from_slice(
            x25519
                .compute_public_key()
                .map_err(|_| anyhow::anyhow!("x25519"))?
                .as_ref(),
        );
        offer.extend_from_slice(
            mlkem
                .encapsulation_key()
                .map_err(|_| anyhow::anyhow!("ml-kem-1024"))?
                .key_bytes()
                .map_err(|_| anyhow::anyhow!("ml-kem-1024"))?
                .as_ref(),
        );
        Ok(InitiatorV2 {
            next,
            x25519,
            mlkem,
            offer,
        })
    }

    fn finish(self, psk: &[u8; 32], answer: &[u8]) -> Result<Keys> {
        use aws_lc_rs::{agreement, kem};
        ensure!(
            answer.len() > SESSION_ID + 32 && answer[..SESSION_ID] == self.next,
            "answer to another offer"
        );
        let peer = agreement::UnparsedPublicKey::new(
            &agreement::X25519,
            &answer[SESSION_ID..SESSION_ID + 32],
        );
        let mut secrets = zeroize::Zeroizing::new(agreement::agree_ephemeral(
            self.x25519,
            peer,
            anyhow::anyhow!("x25519"),
            |k| Ok(k.to_vec()),
        )?);
        let ct = kem::Ciphertext::from(&answer[SESSION_ID + 32..]);
        let k = self
            .mlkem
            .decapsulate(ct)
            .map_err(|_| anyhow::anyhow!("ml-kem-1024 decapsulation"))?;
        secrets.extend_from_slice(k.as_ref());
        session_keys_v2(psk, &self.offer, answer, &secrets)
    }
}

/// Link v2 responder: ephemeral X25519 + ML-KEM-1024 encapsulation + dual-PRF KDF.
fn respond_v2(psk: &[u8; 32], offer: &[u8]) -> Result<(Vec<u8>, Keys)> {
    use aws_lc_rs::{agreement, kem};
    ensure!(offer.len() > SESSION_ID + 32, "short v2 offer");
    let rng = SystemRandom::new();
    let mine = agreement::EphemeralPrivateKey::generate(&agreement::X25519, &rng)
        .map_err(|_| anyhow::anyhow!("x25519 keygen"))?;
    let mut answer = offer[..SESSION_ID].to_vec();
    answer.extend_from_slice(
        mine.compute_public_key()
            .map_err(|_| anyhow::anyhow!("x25519"))?
            .as_ref(),
    );
    let peer =
        agreement::UnparsedPublicKey::new(&agreement::X25519, &offer[SESSION_ID..SESSION_ID + 32]);
    let mut secrets = zeroize::Zeroizing::new(agreement::agree_ephemeral(
        mine,
        peer,
        anyhow::anyhow!("x25519"),
        |k| Ok(k.to_vec()),
    )?);
    let ek = kem::EncapsulationKey::new(&kem::ML_KEM_1024, &offer[SESSION_ID + 32..])
        .map_err(|_| anyhow::anyhow!("bad ml-kem-1024 key"))?;
    let (ct, k) = ek
        .encapsulate()
        .map_err(|_| anyhow::anyhow!("ml-kem-1024 encapsulation"))?;
    answer.extend_from_slice(ct.as_ref());
    secrets.extend_from_slice(k.as_ref());
    let keys = session_keys_v2(psk, offer, &answer, &secrets)?;
    Ok((answer, keys))
}

/// The sender's half of one v1 key exchange: its ephemeral keys and the offer it sent.
#[cfg_attr(not(test), allow(dead_code))]
struct Initiator {
    next: [u8; SESSION_ID],
    x25519: aws_lc_rs::agreement::EphemeralPrivateKey,
    mlkem: aws_lc_rs::kem::DecapsulationKey,
    offer: Vec<u8>,
}

#[cfg_attr(not(test), allow(dead_code))]
impl Initiator {
    /// Fresh ephemeral keys; the offer = next session id || X25519 public || ML-KEM-768
    /// encapsulation key.
    fn new() -> Result<Self> {
        use aws_lc_rs::{agreement, kem};
        let rng = SystemRandom::new();
        let mut next = [0u8; SESSION_ID];
        rng.fill(&mut next)
            .map_err(|_| anyhow::anyhow!("no randomness"))?;
        let x25519 = agreement::EphemeralPrivateKey::generate(&agreement::X25519, &rng)
            .map_err(|_| anyhow::anyhow!("x25519 keygen"))?;
        let mlkem = kem::DecapsulationKey::generate(&kem::ML_KEM_768)
            .map_err(|_| anyhow::anyhow!("ml-kem keygen"))?;
        let mut offer = next.to_vec();
        offer.extend_from_slice(
            x25519
                .compute_public_key()
                .map_err(|_| anyhow::anyhow!("x25519"))?
                .as_ref(),
        );
        offer.extend_from_slice(
            mlkem
                .encapsulation_key()
                .map_err(|_| anyhow::anyhow!("ml-kem"))?
                .key_bytes()
                .map_err(|_| anyhow::anyhow!("ml-kem"))?
                .as_ref(),
        );
        Ok(Initiator {
            next,
            x25519,
            mlkem,
            offer,
        })
    }
    /// Finish with the next hop's answer (next id || X25519 public || ML-KEM ciphertext):
    /// the next session's (forward, reverse) keys. Consumes, and so erases, the ephemerals.
    fn finish(self, psk: &[u8; 32], answer: &[u8]) -> Result<Keys> {
        use aws_lc_rs::{agreement, kem};
        ensure!(
            answer.len() > SESSION_ID + 32 && answer[..SESSION_ID] == self.next,
            "answer to another offer"
        );
        let peer = agreement::UnparsedPublicKey::new(
            &agreement::X25519,
            &answer[SESSION_ID..SESSION_ID + 32],
        );
        let mut secrets = zeroize::Zeroizing::new(agreement::agree_ephemeral(
            self.x25519,
            peer,
            anyhow::anyhow!("x25519"),
            |k| Ok(k.to_vec()),
        )?);
        let ct = kem::Ciphertext::from(&answer[SESSION_ID + 32..]);
        let k = self
            .mlkem
            .decapsulate(ct)
            .map_err(|_| anyhow::anyhow!("ml-kem decapsulation"))?;
        secrets.extend_from_slice(k.as_ref());
        session_keys(psk, &self.offer, answer, &secrets)
    }
}

/// The next hop's half: answer `offer`, returning (answer, (forward, reverse) keys).
fn respond(psk: &[u8; 32], offer: &[u8]) -> Result<(Vec<u8>, Keys)> {
    use aws_lc_rs::{agreement, kem};
    ensure!(offer.len() > SESSION_ID + 32, "short offer");
    let rng = SystemRandom::new();
    let mine = agreement::EphemeralPrivateKey::generate(&agreement::X25519, &rng)
        .map_err(|_| anyhow::anyhow!("x25519 keygen"))?;
    let mut answer = offer[..SESSION_ID].to_vec();
    answer.extend_from_slice(
        mine.compute_public_key()
            .map_err(|_| anyhow::anyhow!("x25519"))?
            .as_ref(),
    );
    let peer =
        agreement::UnparsedPublicKey::new(&agreement::X25519, &offer[SESSION_ID..SESSION_ID + 32]);
    let mut secrets = zeroize::Zeroizing::new(agreement::agree_ephemeral(
        mine,
        peer,
        anyhow::anyhow!("x25519"),
        |k| Ok(k.to_vec()),
    )?);
    let ek = kem::EncapsulationKey::new(&kem::ML_KEM_768, &offer[SESSION_ID + 32..])
        .map_err(|_| anyhow::anyhow!("bad ml-kem key"))?;
    let (ct, k) = ek
        .encapsulate()
        .map_err(|_| anyhow::anyhow!("ml-kem encapsulation"))?;
    answer.extend_from_slice(ct.as_ref());
    secrets.extend_from_slice(k.as_ref());
    let keys = session_keys(psk, offer, &answer, &secrets)?;
    Ok((answer, keys))
}

/// A handshake message cut to fit cells: kind, part, parts, bytes.
fn fragments(kind: u8, msg: &[u8], cell: usize) -> Vec<Vec<u8>> {
    let room = cell - 2 - FRAGMENT_HEADER;
    let chunks: Vec<&[u8]> = msg.chunks(room).collect();
    chunks
        .iter()
        .enumerate()
        .map(|(i, c)| [&[kind, i as u8, chunks.len() as u8][..], c].concat())
        .collect()
}

/// Reassembles one handshake message from its fragments.
#[derive(Default)]
struct Assembler {
    kind: u8,
    parts: Vec<Option<Vec<u8>>>,
}

impl Assembler {
    /// Feed one fragment; the whole (kind, message) once every part has arrived.
    fn feed(&mut self, frag: &[u8]) -> Option<(u8, Vec<u8>)> {
        let &[kind, part, parts] = frag.first_chunk::<FRAGMENT_HEADER>()?;
        let data = &frag[FRAGMENT_HEADER..];
        if parts == 0 || part >= parts {
            return None;
        }
        if self.kind != kind || self.parts.len() != parts as usize {
            self.kind = kind;
            self.parts = vec![None; parts as usize];
        }
        self.parts[part as usize] = Some(data.to_vec());
        if self.parts.iter().all(Option::is_some) {
            let msg = self.parts.drain(..).flatten().flatten().collect();
            return Some((kind, msg));
        }
        None
    }
}

/// The state a sending clock shares with its link: the current sealer, handshake
/// fragments to send first, and whether packets may travel yet (only under handshake keys).
struct Lane {
    sealer: std::sync::Mutex<Sealer>,
    control: std::sync::Mutex<std::collections::VecDeque<Vec<u8>>>,
    secure: std::sync::atomic::AtomicBool,
}

impl Lane {
    fn new(sealer: Sealer) -> Arc<Self> {
        Arc::new(Lane {
            sealer: std::sync::Mutex::new(sealer),
            control: std::sync::Mutex::new(std::collections::VecDeque::new()),
            secure: std::sync::atomic::AtomicBool::new(false),
        })
    }
    /// Queue handshake fragments (bounded: a backlog is pointless, the sender resends).
    fn push_control(&self, frags: Vec<Vec<u8>>) {
        if let Ok(mut q) = self.control.lock()
            && q.len() < 8
        {
            q.extend(frags);
        }
    }
    /// Switch to the session from a handshake: packets may travel from now on.
    fn rekey(&self, id: [u8; SESSION_ID], key: &[u8; 32]) -> Result<()> {
        let sealer = Sealer::keyed(id, key)?;
        *self
            .sealer
            .lock()
            .map_err(|_| anyhow::anyhow!("lane poisoned"))? = sealer;
        self.secure.store(true, Ordering::SeqCst);
        Ok(())
    }
}

/// Aborts its tasks when dropped, so a link never outlives the session that owns it.
pub struct Guard(Vec<AbortHandle>);

impl Guard {
    /// Guard one task.
    pub fn new<T>(task: JoinHandle<T>) -> Self {
        Guard(vec![task.abort_handle()])
    }
    fn all(tasks: Vec<JoinHandle<()>>) -> Self {
        Guard(tasks.iter().map(JoinHandle::abort_handle).collect())
    }
}

impl Drop for Guard {
    fn drop(&mut self) {
        for t in &self.0 {
            t.abort();
        }
    }
}

/// Where a link's cells go: a UDP socket (the default), or a TCP stream, for a next hop
/// reachable only over TCP (an IPv6-only host whose provider carries no UDP there). On a
/// stream every cell is written whole and cells are all one size, so the receiver reads
/// exactly one cell at a time: no framing that a cell's contents could influence.
#[derive(Clone)]
enum Wire {
    Udp {
        socket: Arc<UdpSocket>,
        peer: Option<SocketAddr>,
    },
    /// Cells for the stream's writer task. A full buffer (a stalled connection) drops
    /// the cell, as a lost datagram would: the clock never waits and never bursts.
    Stream(mpsc::Sender<Vec<u8>>),
}

impl Wire {
    async fn put(&self, cell: Vec<u8>) {
        // A refused or unreachable next hop is not fatal: keep the clock.
        match self {
            Wire::Udp { socket, peer } => {
                let _ = match peer {
                    Some(p) => socket.send_to(&cell, *p).await,
                    None => socket.send(&cell).await,
                };
            }
            Wire::Stream(tx) => {
                let _ = tx.try_send(cell);
            }
        }
    }
}

/// How many sealed cells may wait for a stream's writer: a second of the clock at most.
fn stream_buffer(pace: Pace) -> usize {
    (pace.per_second().ceil() as usize).max(8)
}

/// Send `slots` cells to the wire every tick of `pace` on a drift-free grid: queued
/// packets first, dummies for the rest. With `credit`, each cell spends one credit and
/// a tick without credit sends nothing more (never a burst later).
async fn clock(
    wire: Wire,
    mut queue: mpsc::Receiver<Bytes>,
    lane: Arc<Lane>,
    pace: Pace,
    cell: usize,
    credit: Option<Arc<AtomicU64>>,
) {
    let mut tick = interval(pace.clock);
    // A late tick is skipped, not made up: making it up would be a burst.
    tick.set_missed_tick_behavior(MissedTickBehavior::Skip);
    loop {
        tick.tick().await;
        for _ in 0..pace.slots {
            if let Some(c) = &credit
                && c.fetch_update(Ordering::SeqCst, Ordering::SeqCst, spend)
                    .is_err()
            {
                break;
            }
            // A handshake fragment first; packets only once the session is keyed by a
            // handshake (until then they wait in the queue); a dummy otherwise.
            let control = lane.control.lock().ok().and_then(|mut q| q.pop_front());
            let sealed = {
                let Ok(mut sealer) = lane.sealer.lock() else {
                    return;
                };
                if let Some(msg) = control {
                    sealer.seal_control(&msg, cell)
                } else {
                    let payload = if lane.secure.load(Ordering::SeqCst) {
                        match queue.try_recv() {
                            Ok(p) => p,
                            Err(TryRecvError::Empty) => Bytes::new(),
                            Err(TryRecvError::Disconnected) => return,
                        }
                    } else {
                        Bytes::new()
                    };
                    sealer.seal(&payload, cell)
                }
            };
            let Ok(sealed) = sealed else {
                return;
            };
            wire.put(sealed).await;
        }
    }
}

/// A relay's paced link to its next hop. Send packets with [`Egress::send`]; packets
/// the next hop sends back arrive on `rx`.
pub struct Egress {
    tx: mpsc::Sender<Bytes>,
    /// Packets from the next hop (dummies already removed).
    pub rx: mpsc::Receiver<Bytes>,
    born: Instant,
    /// Milliseconds after `born` of the last authenticated cell from the next hop
    /// (u64::MAX: none yet). A live next hop answers every tick, dummies included.
    heard: Arc<AtomicU64>,
    _guard: Guard,
}

impl Egress {
    /// How long since the next hop was last heard, or `None` if it never was.
    pub fn silent_for(&self) -> Option<Duration> {
        match self.heard.load(Ordering::SeqCst) {
            u64::MAX => None,
            ms => Some(
                self.born
                    .elapsed()
                    .saturating_sub(Duration::from_millis(ms)),
            ),
        }
    }
    /// Wait up to `limit` for the next hop's first authenticated cell: whether it is live.
    pub async fn alive_within(&self, limit: Duration) -> bool {
        let end = Instant::now() + limit;
        while Instant::now() < end {
            if self.silent_for().is_some() {
                return true;
            }
            tokio::time::sleep(Duration::from_millis(20)).await;
        }
        false
    }
    /// Queue one packet for the next tick with room. `false`: the queue is full and the
    /// packet was dropped (a bottleneck, never a burst).
    pub fn send(&self, packet: &[u8]) -> bool {
        self.tx.try_send(Bytes::copy_from_slice(packet)).is_ok()
    }
}

/// Open a paced link from this relay to `next` on `psk` (key exchange every [`REKEY`]).
pub async fn egress(next: SocketAddr, psk: [u8; 32], pace: Pace, cell: usize) -> Result<Egress> {
    egress_rekeying(next, psk, pace, cell, REKEY).await
}

/// [`egress`] over TCP: the same cells, clock, keys and handshake on one stream to
/// `next`, reconnected (with a fresh key exchange at once) whenever it drops.
pub async fn egress_tcp(
    next: SocketAddr,
    psk: [u8; 32],
    pace: Pace,
    cell: usize,
) -> Result<Egress> {
    egress_tcp_rekeying(next, psk, pace, cell, REKEY).await
}

/// The parts of a relay's link that do not depend on the transport.
struct EgressCore {
    opener: Arc<std::sync::Mutex<Opener>>,
    answers: mpsc::Sender<Vec<u8>>,
    deliver: mpsc::Sender<Bytes>,
    born: Instant,
    heard: Arc<AtomicU64>,
}

impl EgressCore {
    /// One cell from the next hop: note that it is alive, collect handshake answers and
    /// deliver packets (never one under a PSK-only key).
    fn take(&self, wire: &[u8], cell: usize, assembler: &mut Assembler) {
        let Some(o) = self
            .opener
            .lock()
            .ok()
            .and_then(|mut op| op.open_cell(wire, cell))
        else {
            return;
        };
        self.heard
            .store(self.born.elapsed().as_millis() as u64, Ordering::SeqCst);
        if o.control {
            if let Some((ANSWER | ANSWER_V2, msg)) = assembler.feed(&o.payload) {
                let _ = self.answers.try_send(msg);
            }
        } else if !o.payload.is_empty() && o.rekeyed {
            let _ = self.deliver.try_send(Bytes::from(o.payload));
        }
    }
}

/// Build the transport-independent state, its clock on `wire` and the key exchange
/// (offer until answered, switch, wait `every` or a `kick`, again).
fn egress_parts(
    wire: Wire,
    psk: [u8; 32],
    pace: Pace,
    cell: usize,
    every: Duration,
    kick: Arc<Notify>,
) -> Result<(Arc<EgressCore>, Egress, Vec<JoinHandle<()>>)> {
    let (tx, queue) = mpsc::channel(pace.queue());
    let (deliver, rx) = mpsc::channel(pace.queue());
    let born = Instant::now();
    let heard = Arc::new(AtomicU64::new(u64::MAX));
    let lane = Lane::new(Sealer::new(&psk, Dir::Forward)?);
    let opener = Arc::new(std::sync::Mutex::new(Opener::new(vec![psk], Dir::Reverse)));
    let (answers, mut answered) = mpsc::channel::<Vec<u8>>(4);
    let sender = tokio::spawn(clock(wire, queue, lane.clone(), pace, cell, None));
    let core = Arc::new(EgressCore {
        opener: opener.clone(),
        answers,
        deliver,
        born,
        heard: heard.clone(),
    });
    let handshake = tokio::spawn(async move {
        loop {
            let Ok(me) = InitiatorV2::new() else { return };
            let next = me.next;
            let frags = fragments(OFFER_V2, &me.offer, cell);
            let answer = loop {
                lane.push_control(frags.clone());
                match tokio::time::timeout(OFFER_EVERY, answered.recv()).await {
                    Ok(Some(a)) if a.get(..SESSION_ID) == Some(&next[..]) => break a,
                    Ok(None) => return,
                    _ => {}
                }
            };
            let Ok(keys) = me.finish(&psk, &answer) else {
                continue;
            };
            let (fwd, rev) = (
                zeroize::Zeroizing::new(keys.0),
                zeroize::Zeroizing::new(keys.1),
            );
            if let Ok(mut op) = opener.lock() {
                op.add_session(next, 0, &rev, None);
            }
            if lane.rekey(next, &fwd).is_err() {
                return;
            }
            // A new stream starts a new exchange at once: the next hop's state for the
            // old one is gone, and its replies would otherwise wait for the next rekey.
            tokio::select! {
                _ = tokio::time::sleep(every) => {}
                _ = kick.notified() => {}
            }
        }
    });
    let link = Egress {
        tx,
        rx,
        born,
        heard,
        _guard: Guard(Vec::new()),
    };
    Ok((core, link, vec![sender, handshake]))
}

/// [`egress`] with its own rekey interval (tests).
async fn egress_rekeying(
    next: SocketAddr,
    psk: [u8; 32],
    pace: Pace,
    cell: usize,
    every: Duration,
) -> Result<Egress> {
    let any = if next.is_ipv6() {
        "[::]:0"
    } else {
        "0.0.0.0:0"
    };
    let socket = Arc::new(UdpSocket::bind(any).await?);
    socket.connect(next).await?;
    let wire = Wire::Udp {
        socket: socket.clone(),
        peer: None,
    };
    let (core, mut link, mut tasks) =
        egress_parts(wire, psk, pace, cell, every, Arc::new(Notify::new()))?;
    tasks.push(tokio::spawn(async move {
        let mut buf = vec![0u8; 65536];
        let mut assembler = Assembler::default();
        loop {
            let Ok(n) = socket.recv(&mut buf).await else {
                // ICMP-refused while the next hop is down: keep listening.
                tokio::time::sleep(Duration::from_millis(100)).await;
                continue;
            };
            core.take(&buf[..n], cell, &mut assembler);
        }
    }));
    link._guard = Guard::all(tasks);
    Ok(link)
}

/// [`egress_tcp`] with its own rekey interval (tests).
async fn egress_tcp_rekeying(
    next: SocketAddr,
    psk: [u8; 32],
    pace: Pace,
    cell: usize,
    every: Duration,
) -> Result<Egress> {
    let (cells, mut pending) = mpsc::channel::<Vec<u8>>(stream_buffer(pace));
    let kick = Arc::new(Notify::new());
    let (core, mut link, mut tasks) =
        egress_parts(Wire::Stream(cells), psk, pace, cell, every, kick.clone())?;
    let size = OVERHEAD + cell;
    tasks.push(tokio::spawn(async move {
        let mut first = true;
        loop {
            let Ok(Ok(stream)) =
                tokio::time::timeout(Duration::from_secs(10), TcpStream::connect(next)).await
            else {
                // Down or unreachable: cells meanwhile are dropped, as lost datagrams.
                while pending.try_recv().is_ok() {}
                tokio::time::sleep(Duration::from_secs(1)).await;
                continue;
            };
            let _ = stream.set_nodelay(true); // one segment per cell, as the clock sends them
            let (mut rd, mut wr) = stream.into_split();
            while pending.try_recv().is_ok() {} // stale cells from while it was down
            if !first {
                kick.notify_one();
            }
            first = false;
            let core = core.clone();
            let reader = tokio::spawn(async move {
                let mut buf = vec![0u8; size];
                let mut assembler = Assembler::default();
                while rd.read_exact(&mut buf).await.is_ok() {
                    core.take(&buf, cell, &mut assembler);
                }
            });
            let _reader = Guard::new(reader);
            while let Some(c) = pending.recv().await {
                if wr.write_all(&c).await.is_err() {
                    break;
                }
                if _reader.0[0].is_finished() {
                    break;
                }
            }
            tokio::time::sleep(Duration::from_millis(200)).await;
        }
    }));
    link._guard = Guard::all(tasks);
    Ok(link)
}

struct Peer {
    last: Instant,
    credit: Arc<AtomicU64>,
    local: Arc<UdpSocket>,
    lane: Arc<Lane>,
    assembler: Assembler,
    /// The last offer answered: its session id, our answer (resent if the offer comes
    /// again: the answer was lost) and our reply key, held until the sender switches.
    answered: Option<Answered>,
    _guard: Guard,
}

/// A new peer's state, its paced replies on `wire` and its packets from the local QUIC
/// endpoint at `quic`. Called only after its first cell authenticated.
async fn new_peer(
    wire: Wire,
    quic: SocketAddr,
    psk: &[u8; 32],
    pace: Pace,
    cell: usize,
) -> Result<Peer> {
    let local = Arc::new(UdpSocket::bind("127.0.0.1:0").await?);
    local.connect(quic).await?;
    let (tx, queue) = mpsc::channel::<Bytes>(pace.queue());
    let credit = Arc::new(AtomicU64::new(0));
    let lane = Lane::new(Sealer::new(psk, Dir::Reverse)?);
    let pacer = tokio::spawn(clock(
        wire,
        queue,
        lane.clone(),
        pace,
        cell,
        Some(credit.clone()),
    ));
    let reader = {
        let local = local.clone();
        tokio::spawn(async move {
            let mut b = vec![0u8; 65536];
            while let Ok(n) = local.recv(&mut b).await {
                // Full queue: drop, as a bottleneck would.
                let _ = tx.try_send(Bytes::copy_from_slice(&b[..n]));
            }
        })
    };
    Ok(Peer {
        last: Instant::now(),
        credit,
        local,
        lane,
        assembler: Assembler::default(),
        answered: None,
        _guard: Guard::all(vec![pacer, reader]),
    })
}

/// One authenticated cell from `peer`: earn reply credit, follow its key exchange, and
/// return the packet to forward to the local QUIC endpoint, if it carries one under a
/// handshake key (never one under a PSK-only key). The same on UDP and TCP.
fn admit(
    peer: &mut Peer,
    opener: &mut Opener,
    psks: &[[u8; 32]],
    o: Opened,
    cell: usize,
    cap: u64,
) -> Option<Vec<u8>> {
    peer.last = Instant::now();
    let _ = peer
        .credit
        .fetch_update(Ordering::SeqCst, Ordering::SeqCst, |c| Some(earn(c, cap)));
    // The sender has switched to the session we answered: reply under it too.
    if let Some((next, _, rev)) = &mut peer.answered
        && *next == o.id
        && let Some(key) = rev.take()
    {
        let _ = peer.lane.rekey(*next, &key);
    }
    if o.control {
        if let Some((kind @ (OFFER | OFFER_V2), offer)) = peer.assembler.feed(&o.payload) {
            let answer_kind = if kind == OFFER_V2 { ANSWER_V2 } else { ANSWER };
            match &peer.answered {
                // The same offer again: our answer was lost; resend it unchanged.
                Some((next, answer, _)) if offer.get(..SESSION_ID) == Some(&next[..]) => {
                    peer.lane.push_control(fragments(answer_kind, answer, cell));
                }
                _ => {
                    let res = if kind == OFFER_V2 {
                        respond_v2(&psks[o.index], &offer)
                    } else {
                        respond(&psks[o.index], &offer)
                    };
                    if let Ok((answer, (fwd, rev))) = res {
                        let fwd = zeroize::Zeroizing::new(fwd);
                        let next: [u8; SESSION_ID] = answer[..SESSION_ID].try_into().expect("id");
                        opener.add_session(next, o.index, &fwd, Some(o.id));
                        peer.lane
                            .push_control(fragments(answer_kind, &answer, cell));
                        peer.answered = Some((next, answer, Some(zeroize::Zeroizing::new(rev))));
                    }
                }
            }
        }
        None
    } else if !o.payload.is_empty() && o.rekeyed {
        Some(o.payload)
    } else {
        None
    }
}

/// The receiving end of paced links: listen on `public`, admit only authenticated
/// cells under `psks`, hand their packets to the local QUIC endpoint at `quic`, and
/// pace its replies back to each peer on credit. At most `max_peers` peers at once.
pub async fn ingress(
    public: SocketAddr,
    quic: SocketAddr,
    psks: Vec<[u8; 32]>,
    pace: Pace,
    cell: usize,
    max_peers: usize,
) -> Result<()> {
    if psks.is_empty() {
        bail!("paced ingress needs at least one link key");
    }
    let socket = Arc::new(UdpSocket::bind(public).await.context("link listen")?);
    let mut peers: HashMap<SocketAddr, Peer> = HashMap::new();
    let mut opener = Opener::new(psks.clone(), Dir::Forward);
    let mut buf = vec![0u8; 65536];
    let mut sweep = interval(Duration::from_secs(1));
    let cap = CREDIT_TICKS * pace.slots as u64;
    loop {
        tokio::select! {
            _ = sweep.tick() => {
                peers.retain(|_, p| p.last.elapsed() < PEER_IDLE);
            }
            r = socket.recv_from(&mut buf) => {
                let Ok((n, from)) = r else { continue };
                // Authenticate first: an unauthenticated packet creates no state.
                let Some(o) = opener.open_cell(&buf[..n], cell) else { continue };
                if !peers.contains_key(&from) {
                    if peers.len() >= max_peers {
                        continue;
                    }
                    let wire = Wire::Udp { socket: socket.clone(), peer: Some(from) };
                    let peer = new_peer(wire, quic, &psks[o.index], pace, cell).await?;
                    peers.insert(from, peer);
                }
                let peer = peers.get_mut(&from).expect("just inserted");
                if let Some(packet) = admit(peer, &mut opener, &psks, o, cell, cap) {
                    let _ = peer.local.send(&packet).await;
                }
            }
        }
    }
}

/// How long a new TCP connection may take to send its first authenticated cell before
/// it is closed: an unauthenticated connection holds no peer state, only this wait.
const FIRST_CELL: Duration = Duration::from_secs(10);

/// [`ingress`] over TCP: each connection is one peer, admitted only once its first cell
/// authenticates (nothing is ever sent to a connection that has not), with the same
/// credit, key exchange and peer limit. Its replies go back on the same connection.
pub async fn ingress_tcp(
    public: SocketAddr,
    quic: SocketAddr,
    psks: Vec<[u8; 32]>,
    pace: Pace,
    cell: usize,
    max_peers: usize,
) -> Result<()> {
    if psks.is_empty() {
        bail!("paced ingress needs at least one link key");
    }
    let listener = TcpListener::bind(public).await.context("link listen")?;
    let opener = Arc::new(std::sync::Mutex::new(Opener::new(
        psks.clone(),
        Dir::Forward,
    )));
    let psks = Arc::new(psks);
    // Every connection's task lives in this set: when the ingress stops (its guard is
    // dropped, the server restarts), they all stop with it, and their state is gone.
    let mut peers = tokio::task::JoinSet::new();
    loop {
        tokio::select! {
            accepted = listener.accept() => {
                let Ok((stream, _)) = accepted else {
                    tokio::time::sleep(Duration::from_millis(50)).await;
                    continue;
                };
                if peers.len() >= max_peers {
                    continue; // dropped: closed without a byte
                }
                let (opener, psks) = (opener.clone(), psks.clone());
                peers.spawn(async move {
                    let _ = serve_tcp_peer(stream, quic, &psks, &opener, pace, cell).await;
                });
            }
            Some(_) = peers.join_next(), if !peers.is_empty() => {}
        }
    }
}

async fn serve_tcp_peer(
    stream: TcpStream,
    quic: SocketAddr,
    psks: &[[u8; 32]],
    opener: &std::sync::Mutex<Opener>,
    pace: Pace,
    cell: usize,
) -> Result<()> {
    let _ = stream.set_nodelay(true);
    let (mut rd, mut wr) = stream.into_split();
    let mut buf = vec![0u8; OVERHEAD + cell];
    tokio::time::timeout(FIRST_CELL, rd.read_exact(&mut buf))
        .await
        .context("no first cell")??;
    let open = |b: &[u8]| opener.lock().ok().and_then(|mut op| op.open_cell(b, cell));
    let Some(first) = open(&buf) else {
        bail!("first cell did not authenticate");
    };
    let (cells, mut pending) = mpsc::channel::<Vec<u8>>(stream_buffer(pace));
    let writer = tokio::spawn(async move {
        while let Some(c) = pending.recv().await {
            if wr.write_all(&c).await.is_err() {
                return;
            }
        }
    });
    let _writer = Guard::new(writer);
    let mut peer = new_peer(Wire::Stream(cells), quic, &psks[first.index], pace, cell).await?;
    let cap = CREDIT_TICKS * pace.slots as u64;
    let mut next = Some(first);
    loop {
        if let Some(o) = next.take() {
            let packet = {
                let Ok(mut op) = opener.lock() else {
                    bail!("opener poisoned")
                };
                admit(&mut peer, &mut op, psks, o, cell, cap)
            };
            if let Some(packet) = packet {
                let _ = peer.local.send(&packet).await;
            }
        }
        // A live sender sends a cell every tick: silence means it is gone.
        match tokio::time::timeout(PEER_IDLE, rd.read_exact(&mut buf)).await {
            Ok(Ok(_)) => next = open(&buf),
            _ => return Ok(()),
        }
    }
}

