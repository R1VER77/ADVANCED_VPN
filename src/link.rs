#[cfg(test)]
mod guard_tests {
    use super::*;

    #[tokio::test]
    async fn dropping_the_guard_stops_the_task() {
        let (tx, mut rx) = mpsc::channel::<()>(1);
        let task = tokio::spawn(async move {
            let _tx = tx;
            std::future::pending::<()>().await;
        });
        drop(Guard::new(task));
        // The task's sender is dropped only when the task really ends.
        let r = tokio::time::timeout(Duration::from_secs(1), rx.recv()).await;
        assert!(matches!(r, Ok(None)), "the guarded task is still running");
    }
}
