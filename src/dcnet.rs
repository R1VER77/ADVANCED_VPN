    #[test]
    fn collision_detected_and_identical_edge() {
        let ev = test_event();
        let mut ev_b = test_event();
        ev_b.nonce = 0x9988_7766_5544_3322;
        let mut members = cell4();
        // Different nonces: garbled.
        let sum = sum_round(&mut members, VEC_ROUND, |i| match i {
            1 => Some(&ev),
            3 => Some(&ev_b),
            _ => None,
        });
        assert_eq!(DcEvent::decode(&sum), DcOutcome::Garbled);
        // Identical encodings from two senders cancel to Null (documented edge:
        // duplicate events are indistinguishable from no event).
        let sum = sum_round(&mut members, VEC_ROUND + 1, |i| {
            (i == 1 || i == 3).then_some(&ev)
        });
        assert_eq!(DcEvent::decode(&sum), DcOutcome::Null);
    }

