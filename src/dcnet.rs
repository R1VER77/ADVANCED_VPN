    #[test]
    fn a_chain_pad_is_taken_once_and_the_state_only_moves_forward() {
        let mut r = ratchet01();
        let p = r.take(VEC_ROUND).unwrap();
        assert_eq!(r.take(VEC_ROUND), Err(DcError::PadUsed));
        assert_eq!(r.take(VEC_ROUND - 1), Err(DcError::PadUsed));
        // The state now is round 78's; from it nothing gives round 77 again, and its next
        // pad differs. (That no earlier state follows from it is SHA-256's one-wayness.)
        assert_eq!(r.next, VEC_ROUND + 1);
        let mut captured = Ratchet::new(r.next, r.state);
        assert_eq!(captured.take(VEC_ROUND), Err(DcError::PadUsed));
        assert_ne!(captured.take(VEC_ROUND + 1).unwrap(), p);
        assert_ne!(r.state, sha256(b"vec-ratchet-0-1"));
    }

    #[test]
    fn a_cell_can_mix_in_person_books_and_network_chains() {
        // Pairs (0,1) and (2,3) on chains, the others on books, as dcnet_reference.py.
        let ev = test_event();
        let chained = |a: usize, b: usize| (a, b) == (0, 1) || (a, b) == (2, 3);
        let mut members: Vec<CellPads> = (0..4)
            .map(|i| {
                let books = (0..4)
                    .filter(|&j| j != i)
                    .map(|j| {
                        let (a, b) = (i.min(j), i.max(j));
                        if chained(a, b) {
                            PairPads::Ratchet(Ratchet::new(
                                VEC_FIRST_ROUND,
                                sha256(format!("vec-ratchet-{a}-{b}").as_bytes()),
                            ))
                        } else {
                            PairPads::OneTime(
                                PadBook::new(VEC_FIRST_ROUND, book_bytes("vec-book", a, b))
                                    .unwrap(),
                            )
                        }
                    })
                    .collect();
                CellPads::new(4, i, books).unwrap()
            })
            .collect();
        let sum = sum_round(&mut members, VEC_ROUND, |i| (i == 1).then_some(&ev));
        assert_eq!(DcEvent::decode(&sum), DcOutcome::Event(ev));
        let null = sum_round(&mut members, VEC_ROUND + 1, |_| None);
        assert_eq!(DcEvent::decode(&null), DcOutcome::Null);
    }
