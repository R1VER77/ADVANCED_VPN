//! DC-net control channel for AVPN/Mesh — see `docs/DCNET_CONTROL_DESIGN.md`.
//!
//! Scope of this module: round core, frame codec, pairwise-pad derivation,
//! group aggregation and decoding. Cell assignment, gossip round-sync, and
//! blinded-registry MAC verification are wired at the integration layer
//! (`avpn mesh`), not here.
//!
//! Security claim (computational, NOT information-theoretic): sender
//! unlinkability within a cell rests on PRG-derived pads seeded by pairwise
//! keys established at enrollment. Read design doc §2 before writing any
//! public claim that references this module.
//!
//! Byte-exact cross-language verification: the golden vectors in the test
//! module below are generated by `tools/dcnet_reference.py` (Python mirror
//! of this construction) and stored in `docs/evidence/DCNET_VECTORS.json`.
//! Regenerate with: `python3 tools/dcnet_reference.py`.
//!
//! Wire construction:
//! ```text
//! seed_ij(cell)  = HKDF-SHA256(ikm = K_ij, salt = 0^32,
//!                              info = "dc-pad" || cell_id_be4)[..32]
//! pad_ij(round)  = PRG(seed_ij, "dc-round-<round decimal>")   // SHA256-CTR
//! body_i         = event_i? XOR (XOR over partners j of pad_ij)
//! frame          = magic(2) || cell_id(4) || round(8) || flags(1)
//!                  || body(64) || member_mac(32)               // 111 bytes
//! group decode   = XOR of all bodies of one (cell, round):
//!                  all-zero => Null, valid CRC-8 + encoding => Event,
//!                  anything else => Garbled (collision or jam)
//! ```

use hmac::{Hmac, Mac};
use sha2::{Digest, Sha256};

/// Total frame length: header, body and member MAC.
pub const FRAME_LEN: usize = 111;
/// Frame header: magic(2), cell id(4), round(8), flags(1).
pub const HEADER_LEN: usize = 15; // magic(2)+cell(4)+round(8)+flags(1)
/// The XOR-combined body each member broadcasts every round.
pub const BODY_LEN: usize = 64;
/// Member MAC (HMAC-SHA256 under the per-epoch anonymous key).
pub const MAC_LEN: usize = 32;
/// Frame magic: identifies a DC-net frame.
pub const MAGIC: u16 = 0xDC4E;

/// Cell sizing bounds (design doc §1.1).
pub const MIN_CELL_SIZE: usize = 12;
/// Largest cell: beyond this the O(n) round traffic outweighs the gain.
pub const MAX_CELL_SIZE: usize = 60;
/// Round cadence (design doc §1.2).
pub const ROUND_SECS: u64 = 5;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
/// Why a cell, a frame set or a round was refused.
pub enum DcError {
    /// Cell size out of bounds, index outside the cell, or wrong pairwise-key count.
    BadPads,
    /// A round with no frames.
    NoFrames,
    /// Frames from different cells or rounds: a protocol violation, the round aborts.
    RoundMismatch,
    /// A frame that is not a DC-net frame.
    BadMagic,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
/// The four control events the channel carries (design doc §0).
pub enum EventType {
    /// Someone is joining, before their hardware identity is established.
    EnrollIntent = 1,
    /// Binds a chain descriptor to a session without naming its builder.
    ChainSetupCommit = 2,
    /// A member's node keys changed (the TOFU re-verification event).
    KeyRotationNotice = 3,
    /// A member stopped using the mix lane (the event most tied to coercion).
    MixLaneFallback = 4,
}

impl EventType {
    fn from_byte(b: u8) -> Option<Self> {
        match b {
            1 => Some(EventType::EnrollIntent),
            2 => Some(EventType::ChainSetupCommit),
            3 => Some(EventType::KeyRotationNotice),
            4 => Some(EventType::MixLaneFallback),
            _ => None,
        }
    }
}

/// One control event, encoded into a single reserved round slot.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DcEvent {
    /// Which event.
    pub kind: EventType,
    /// Sender's private nonce: separates colliding events and keys the backoff.
    pub nonce: u64,
    /// Event payload, zero-padded.
    pub payload: [u8; 46],
}

/// Outcome of a group decode.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DcOutcome {
    /// All members contributed pads only.
    Null,
    /// Exactly one member sent an event; the aggregate decoded cleanly.
    Event(DcEvent),
    /// CRC/structure failure: collision, jam, or stale replay.
    /// Policy (design doc §4–§5): drop, no side channel, no tracing.
    Garbled,
}

fn sha256(data: &[u8]) -> [u8; 32] {
    let mut h = Sha256::new();
    h.update(data);
    let out = h.finalize();
    let mut r = [0u8; 32];
    r.copy_from_slice(&out);
    r
}

/// SHA-256 counter-mode PRG: out = H(seed || ctx || u32_be(ctr)), ctr from 0.
fn prg(seed: &[u8], ctx: &[u8], out: &mut [u8]) {
    let mut ctr: u32 = 0;
    let mut pos = 0usize;
    while pos < out.len() {
        let mut buf = Vec::with_capacity(seed.len() + ctx.len() + 4);
        buf.extend_from_slice(seed);
        buf.extend_from_slice(ctx);
        buf.extend_from_slice(&ctr.to_be_bytes());
        let d = sha256(&buf);
        let take = (out.len() - pos).min(32);
        out[pos..pos + take].copy_from_slice(&d[..take]);
        pos += take;
        ctr += 1;
    }
}

/// RFC 5869 HKDF-SHA256 with the default salt (32 zero bytes).
fn hkdf_sha256(ikm: &[u8], info: &[u8], out: &mut [u8]) {
    let mut mac = Hmac::<Sha256>::new_from_slice(&[0u8; 32]).expect("hmac accepts any key length");
    mac.update(ikm);
    let prk = mac.finalize().into_bytes();

    let mut t: Vec<u8> = Vec::new();
    let mut ctr: u8 = 1;
    let mut pos = 0usize;
    while pos < out.len() {
        let mut m = Hmac::<Sha256>::new_from_slice(&prk).expect("hmac accepts any key length");
        m.update(&t);
        m.update(info);
        m.update(&[ctr]);
        let block = m.finalize().into_bytes();
        let take = (out.len() - pos).min(32);
        out[pos..pos + take].copy_from_slice(&block[..take]);
        t.clear();
        t.extend_from_slice(&block);
        ctr = ctr.wrapping_add(1);
        pos += take;
    }
}

/// CRC-8 (poly 0x07, init 0x00, no reflect, no final xor) over the event
/// encoding — collision/jam detection input.
fn crc8(data: &[u8]) -> u8 {
    let mut crc: u8 = 0;
    for &byte in data {
        crc ^= byte;
        for _ in 0..8 {
            crc = if crc & 0x80 != 0 {
                (crc << 1) ^ 0x07
            } else {
                crc << 1
            };
        }
    }
    crc
}

impl DcEvent {
    /// Layout: kind(1) || nonce(8) || payload(46) || crc8(1) || zero(8) = 64.
    pub fn encode(&self) -> [u8; BODY_LEN] {
        let mut b = [0u8; BODY_LEN];
        b[0] = self.kind as u8;
        b[1..9].copy_from_slice(&self.nonce.to_be_bytes());
        b[9..55].copy_from_slice(&self.payload);
        b[55] = crc8(&b[..55]);
        b
    }

    /// Decode a group sum: all-zero is a null round, a valid CRC-8 encoding is an event, anything else is garbled (collision or jam).
    pub fn decode(slot: &[u8; BODY_LEN]) -> DcOutcome {
        if slot.iter().all(|&x| x == 0) {
            return DcOutcome::Null;
        }
        if slot[56..64].iter().any(|&x| x != 0) {
            return DcOutcome::Garbled;
        }
        if crc8(&slot[..55]) != slot[55] {
            return DcOutcome::Garbled;
        }
        match EventType::from_byte(slot[0]) {
            None => DcOutcome::Garbled,
            Some(kind) => {
                let mut nonce_bytes = [0u8; 8];
                nonce_bytes.copy_from_slice(&slot[1..9]);
                let mut payload = [0u8; 46];
                payload.copy_from_slice(&slot[9..55]);
                DcOutcome::Event(DcEvent {
                    kind,
                    nonce: u64::from_be_bytes(nonce_bytes),
                    payload,
                })
            }
        }
    }
}

/// Pairwise pad material for one member of one cell.
///
/// `pairwise` holds the master keys K_ij with every OTHER member, ordered
/// by partner index with the member's own index skipped (partner indices
/// below `my_index` first). Symmetric: both members of a pair must seed the
/// same K_ij — established at enrollment via the existing hybrid
/// (ML-KEM-768 + X25519) path and held in the hardware-sealed key store.
pub struct CellPads {
    n: usize,
    my_index: usize,
    pairwise: Vec<[u8; 32]>,
}

impl CellPads {
    /// Pads for member `my_index` of an `n`-member cell, from its n-1 pairwise keys.
    pub fn new(n: usize, my_index: usize, pairwise: Vec<[u8; 32]>) -> Result<Self, DcError> {
        if my_index >= n || pairwise.len() != n - 1 || n < 2 {
            return Err(DcError::BadPads);
        }
        Ok(Self {
            n,
            my_index,
            pairwise,
        })
    }

    /// Cell size.
    pub fn n(&self) -> usize {
        self.n
    }

    fn k_ij(&self, partner: usize) -> &[u8; 32] {
        &self.pairwise[if partner < self.my_index {
            partner
        } else {
            partner - 1
        }]
    }

    /// Per-cell pad seed: HKDF(K_ij, "dc-pad" || cell_id_be4).
    fn cell_seed(&self, partner: usize, cell_id: u32) -> [u8; 32] {
        let mut info = Vec::with_capacity(11);
        info.extend_from_slice(b"dc-pad");
        info.extend_from_slice(&cell_id.to_be_bytes());
        let mut seed = [0u8; 32];
        hkdf_sha256(self.k_ij(partner), &info, &mut seed);
        seed
    }

    /// Per-round pad: PRG(cell_seed, "dc-round-<round>").
    pub fn round_pad(&self, partner: usize, cell_id: u32, round: u64) -> [u8; BODY_LEN] {
        let seed = self.cell_seed(partner, cell_id);
        let ctx = format!("dc-round-{}", round);
        let mut pad = [0u8; BODY_LEN];
        prg(&seed, ctx.as_bytes(), &mut pad);
        pad
    }

    /// This member's 64-byte body for the round. `event = None` is the
    /// silent (null) contribution — still a full pad XOR, never zeros.
    pub fn body(&self, cell_id: u32, round: u64, event: Option<&DcEvent>) -> [u8; BODY_LEN] {
        let mut b = [0u8; BODY_LEN];
        for partner in 0..self.n {
            if partner == self.my_index {
                continue;
            }
            let pad = self.round_pad(partner, cell_id, round);
            for (x, p) in b.iter_mut().zip(pad.iter()) {
                *x ^= p;
            }
        }
        if let Some(ev) = event {
            let enc = ev.encode();
            for (x, e) in b.iter_mut().zip(enc.iter()) {
                *x ^= e;
            }
        }
        b
    }

    /// Full frame for the round (MAC zeroed; the integration layer calls
    /// `Frame::seal` with the per-epoch anonymous MAC key).
    pub fn transmit(&self, cell_id: u32, round: u64, event: Option<&DcEvent>) -> Frame {
        Frame::build(cell_id, round, self.body(cell_id, round, event))
    }
}

/// One member's broadcast frame. Fixed 111 bytes.
#[derive(Debug, Clone)]
pub struct Frame {
    /// The frame on the wire.
    pub bytes: [u8; FRAME_LEN],
}

impl Frame {
    /// Frame a body for (cell, round); the MAC stays zero until [`Frame::seal`].
    pub fn build(cell_id: u32, round: u64, body: [u8; BODY_LEN]) -> Self {
        let mut b = [0u8; FRAME_LEN];
        b[0..2].copy_from_slice(&MAGIC.to_be_bytes());
        b[2..6].copy_from_slice(&cell_id.to_be_bytes());
        b[6..14].copy_from_slice(&round.to_be_bytes());
        b[14] = 0; // flags: constant in v2. MUST NOT encode sender state.
        b[HEADER_LEN..HEADER_LEN + BODY_LEN].copy_from_slice(&body);
        // bytes[79..111]: member_mac, zero until seal()
        Frame { bytes: b }
    }

    /// The frame magic.
    pub fn magic(&self) -> u16 {
        u16::from_be_bytes([self.bytes[0], self.bytes[1]])
    }

    /// The cell this frame belongs to.
    pub fn cell_id(&self) -> u32 {
        let mut b = [0u8; 4];
        b.copy_from_slice(&self.bytes[2..6]);
        u32::from_be_bytes(b)
    }

    /// The round this frame belongs to.
    pub fn round(&self) -> u64 {
        let mut b = [0u8; 8];
        b.copy_from_slice(&self.bytes[6..14]);
        u64::from_be_bytes(b)
    }

    /// The member's 64-byte body.
    pub fn body(&self) -> [u8; BODY_LEN] {
        let mut b = [0u8; BODY_LEN];
        b.copy_from_slice(&self.bytes[HEADER_LEN..HEADER_LEN + BODY_LEN]);
        b
    }

    /// HMAC-SHA256 over the frame prefix under the per-epoch anonymous MAC
    /// key. The key is registered blinded with the directory (blind-RSA
    /// credits machinery) so verification does not identify the member.
    pub fn seal(&mut self, mac_key: &[u8; 32]) {
        let mut m = Hmac::<Sha256>::new_from_slice(mac_key).expect("hmac accepts any key length");
        m.update(&self.bytes[..HEADER_LEN + BODY_LEN]);
        let tag = m.finalize().into_bytes();
        self.bytes[HEADER_LEN + BODY_LEN..FRAME_LEN].copy_from_slice(&tag);
    }

    /// True when the MAC verifies under `mac_key` (cell membership, never member identity).
    pub fn verify(&self, mac_key: &[u8; 32]) -> bool {
        let mut m = Hmac::<Sha256>::new_from_slice(mac_key).expect("hmac accepts any key length");
        m.update(&self.bytes[..HEADER_LEN + BODY_LEN]);
        m.verify_slice(&self.bytes[HEADER_LEN + BODY_LEN..FRAME_LEN])
            .is_ok()
    }
}

/// XOR-aggregate all bodies of one (cell, round) and decode.
///
/// All frames must agree on cell and round; a mixed-round input is an
/// error (the caller aborts the round — design doc §1.2), not `Garbled`,
/// because it indicates a protocol violation rather than a jam.
pub fn group_sum(frames: &[Frame]) -> Result<DcOutcome, DcError> {
    if frames.is_empty() {
        return Err(DcError::NoFrames);
    }
    let cell = frames[0].cell_id();
    let round = frames[0].round();
    for f in frames {
        if f.magic() != MAGIC {
            return Err(DcError::BadMagic);
        }
        if f.cell_id() != cell || f.round() != round {
            return Err(DcError::RoundMismatch);
        }
    }
    let mut sum = [0u8; BODY_LEN];
    for f in frames {
        let b = f.body();
        for (s, x) in sum.iter_mut().zip(b.iter()) {
            *s ^= x;
        }
    }
    Ok(DcEvent::decode(&sum))
}

