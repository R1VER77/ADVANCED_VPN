//! DC-net control channel for AVPN/Mesh — see `docs/DCNET_CONTROL_DESIGN.md`.
//!
//! Scope of this module: round core, frame codec, one-time pad books, group
//! aggregation and decoding. Making, sealing and delivering the books
//! (`tools/padbook.py`), cell assignment, gossip round-sync and blinded-registry
//! MAC verification belong to the integration layer, not here.
//!
//! Each pair's pads come one of two ways, both seeded only by the members' Nitrokeys:
//! - in person: a [`PadBook`] of one-time pads (both members' Nitrokey output XORed),
//!   64 bytes per round, each handed out once and wiped; information-theoretic.
//! - over the network: a [`Ratchet`], a forward-secure chain from a seed both members'
//!   Nitrokeys contributed (sealed in transit with ML-KEM-768 + X25519); computational,
//!   and a captured state gives no earlier round.
//!
//! Sender anonymity is information-theoretic among honest members joined by in-person
//! books (design doc §2, §6). Read §2 before writing any public claim that references
//! this module.
//!
//! Byte-exact cross-language verification: the golden vectors in the test
//! module below are generated by `tools/dcnet_reference.py` (Python mirror
//! of this construction) and stored in `docs/evidence/DCNET_VECTORS.json`.
//! Regenerate with: `python3 tools/dcnet_reference.py`.
//!
//! Wire construction:
//! ```text
//! pad_ij(round)  = book_ij[(round - first_round) * 64 .. + 64], once      (in person)
//!                | SHA256("dc-pad-0" || s_r || r_be8)
//!                  || SHA256("dc-pad-1" || s_r || r_be8),
//!                  s_{r+1} = SHA256("dc-next" || s_r)                  (over the network)
//! body_i         = event_i? XOR (XOR over partners j of pad_ij)
//! frame          = magic(2) || cell_id(4) || round(8) || flags(1)
//!                  || body(64) || member_mac(32)               // 111 bytes
//! group decode   = XOR of all bodies of one (cell, round):
//!                  all-zero => Null, valid CRC-8 + encoding => Event,
//!                  anything else => Garbled (collision or jam)
//! ```

use hmac::{Hmac, Mac};
use sha2::{Digest, Sha256};
use zeroize::Zeroize;

/// Total frame length: header, body and member MAC.
pub const FRAME_LEN: usize = 111;
/// Frame header: magic(2), cell id(4), round(8), flags(1).
pub const HEADER_LEN: usize = 15; // magic(2)+cell(4)+round(8)+flags(1)
/// The XOR-combined body each member broadcasts every round.
pub const BODY_LEN: usize = 64;
/// Member MAC (HMAC-SHA256 under the per-epoch anonymous key).
pub const MAC_LEN: usize = 32;
/// Frame magic: identifies a DC-net frame.
pub const MAGIC: u16 = 0xDC4E;

/// Smallest cell (design doc §1.1): one colluder still leaves three honest members, so
/// no honest pad of a round can be derived (formal/dcnet/dcnet_collusion_4.spthy).
pub const MIN_CELL_SIZE: usize = 4;
/// Largest cell: beyond this the O(n) round traffic and pad books outweigh the gain.
pub const MAX_CELL_SIZE: usize = 60;
/// Round cadence (design doc §1.2): every round burns 64 bytes of each pair's book.
pub const ROUND_SECS: u64 = 30;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
/// Why a cell, a frame set or a round was refused.
pub enum DcError {
    /// Cell size out of bounds, index outside the cell, or wrong pairwise-key count.
    BadPads,
    /// A round with no frames.
    NoFrames,
    /// Frames from different cells or rounds: a protocol violation, the round aborts.
    RoundMismatch,
    /// A frame that is not a DC-net frame.
    BadMagic,
    /// A book has no pad for the round: it is used up. The cell stops (fails closed);
    /// there is no fallback to derived pads.
    PadsExhausted,
    /// The round's pad was already handed out, or the round precedes the book: a pad
    /// is never used twice.
    PadUsed,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
/// The four control events the channel carries (design doc §0).
pub enum EventType {
    /// Someone is joining, before their hardware identity is established.
    EnrollIntent = 1,
    /// Binds a chain descriptor to a session without naming its builder.
    ChainSetupCommit = 2,
    /// A member's node keys changed (the TOFU re-verification event).
    KeyRotationNotice = 3,
    /// A member stopped using the mix lane (the event most tied to coercion).
    MixLaneFallback = 4,
}

impl EventType {
    fn from_byte(b: u8) -> Option<Self> {
        match b {
            1 => Some(EventType::EnrollIntent),
            2 => Some(EventType::ChainSetupCommit),
            3 => Some(EventType::KeyRotationNotice),
            4 => Some(EventType::MixLaneFallback),
            _ => None,
        }
    }
}

/// One control event, encoded into a single reserved round slot.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DcEvent {
    /// Which event.
    pub kind: EventType,
    /// Sender's private nonce: separates colliding events and keys the backoff.
    pub nonce: u64,
    /// Event payload, zero-padded.
    pub payload: [u8; 46],
}

/// Outcome of a group decode.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DcOutcome {
    /// All members contributed pads only.
    Null,
    /// Exactly one member sent an event; the aggregate decoded cleanly.
    Event(DcEvent),
    /// CRC/structure failure: collision, jam, or stale replay.
    /// Policy (design doc §4–§5): drop, no side channel, no tracing.
    Garbled,
}

/// CRC-8 (poly 0x07, init 0x00, no reflect, no final xor) over the event
/// encoding — collision/jam detection input.
fn crc8(data: &[u8]) -> u8 {
    let mut crc: u8 = 0;
    for &byte in data {
        crc ^= byte;
        for _ in 0..8 {
            crc = if crc & 0x80 != 0 {
                (crc << 1) ^ 0x07
            } else {
                crc << 1
            };
        }
    }
    crc
}

impl DcEvent {
    /// Layout: kind(1) || nonce(8) || payload(46) || crc8(1) || zero(8) = 64.
    pub fn encode(&self) -> [u8; BODY_LEN] {
        let mut b = [0u8; BODY_LEN];
        b[0] = self.kind as u8;
        b[1..9].copy_from_slice(&self.nonce.to_be_bytes());
        b[9..55].copy_from_slice(&self.payload);
        b[55] = crc8(&b[..55]);
        b
    }

    /// Decode a group sum: all-zero is a null round, a valid CRC-8 encoding is an event, anything else is garbled (collision or jam).
    pub fn decode(slot: &[u8; BODY_LEN]) -> DcOutcome {
        if slot.iter().all(|&x| x == 0) {
            return DcOutcome::Null;
        }
        if slot[56..64].iter().any(|&x| x != 0) {
            return DcOutcome::Garbled;
        }
        if crc8(&slot[..55]) != slot[55] {
            return DcOutcome::Garbled;
        }
        match EventType::from_byte(slot[0]) {
            None => DcOutcome::Garbled,
            Some(kind) => {
                let mut nonce_bytes = [0u8; 8];
                nonce_bytes.copy_from_slice(&slot[1..9]);
                let mut payload = [0u8; 46];
                payload.copy_from_slice(&slot[9..55]);
                DcOutcome::Event(DcEvent {
                    kind,
                    nonce: u64::from_be_bytes(nonce_bytes),
                    payload,
                })
            }
        }
    }
}

/// One pair's one-time pads in one cell: 64 bytes per round from `first_round`.
///
/// Both members of the pair hold the same bytes (`tools/padbook.py`: each member's
/// Nitrokey output, XORed). [`PadBook::take`] hands each round's pad out once and wipes
/// it, together with any round it skipped; no other way reads the book. Deliberately not
/// `Clone`: a copy would let a pad be used twice.
pub struct PadBook {
    first_round: u64,
    pads: Vec<u8>,
    /// The lowest round still in the book: every earlier pad is wiped.
    next: u64,
}

impl PadBook {
    /// A book of `pads.len() / 64` rounds from `first_round`.
    pub fn new(first_round: u64, pads: Vec<u8>) -> Result<Self, DcError> {
        if pads.is_empty() || !pads.len().is_multiple_of(BODY_LEN) {
            return Err(DcError::BadPads);
        }
        Ok(Self {
            first_round,
            pads,
            next: first_round,
        })
    }

    /// The first round after the book.
    fn end(&self) -> u64 {
        self.first_round + (self.pads.len() / BODY_LEN) as u64
    }

    /// Rounds still in the book.
    pub fn rounds_left(&self) -> u64 {
        self.end() - self.next
    }

    /// Whether `round`'s pad can still be taken, without taking it.
    fn check(&self, round: u64) -> Result<(), DcError> {
        if round < self.next {
            Err(DcError::PadUsed)
        } else if round >= self.end() {
            Err(DcError::PadsExhausted)
        } else {
            Ok(())
        }
    }

    /// The pad of `round`, once. It and every skipped earlier pad are wiped first.
    pub fn take(&mut self, round: u64) -> Result<[u8; BODY_LEN], DcError> {
        self.check(round)?;
        let at = ((round - self.first_round) as usize) * BODY_LEN;
        let from = ((self.next - self.first_round) as usize) * BODY_LEN;
        let mut pad = [0u8; BODY_LEN];
        pad.copy_from_slice(&self.pads[at..at + BODY_LEN]);
        self.pads[from..at + BODY_LEN].zeroize();
        self.next = round + 1;
        Ok(pad)
    }
}

impl Drop for PadBook {
    fn drop(&mut self) {
        self.pads.zeroize();
    }
}

/// One pair's forward-secure pad chain in one cell, for members who cannot meet: the
/// seed is both members' Nitrokey contributions XORed (tools/padbook.py), and each round
/// moves the state one way, so a captured state gives that round and later ones, never
/// an earlier one. Deliberately not `Clone`.
pub struct Ratchet {
    next: u64,
    state: [u8; 32],
}

impl Ratchet {
    /// A chain whose state for `first_round` is `seed`.
    pub fn new(first_round: u64, seed: [u8; 32]) -> Self {
        Self {
            next: first_round,
            state: seed,
        }
    }

    fn check(&self, round: u64) -> Result<(), DcError> {
        if round < self.next {
            Err(DcError::PadUsed)
        } else {
            Ok(())
        }
    }

    fn advance(&mut self) {
        let mut h = Sha256::new();
        h.update(b"dc-next");
        h.update(self.state);
        let next: [u8; 32] = h.finalize().into();
        self.state.zeroize();
        self.state = next;
        self.next += 1;
    }

    /// The pad of `round`, once; the state then moves past it (skipped rounds too).
    pub fn take(&mut self, round: u64) -> Result<[u8; BODY_LEN], DcError> {
        self.check(round)?;
        while self.next < round {
            self.advance();
        }
        let mut pad = [0u8; BODY_LEN];
        for (half, tag) in [(0, b"dc-pad-0"), (1, b"dc-pad-1")] {
            let mut h = Sha256::new();
            h.update(tag);
            h.update(self.state);
            h.update(round.to_be_bytes());
            pad[half * 32..half * 32 + 32].copy_from_slice(&h.finalize());
        }
        self.advance();
        Ok(pad)
    }
}

impl Drop for Ratchet {
    fn drop(&mut self) {
        self.state.zeroize();
    }
}

/// Where one pair's pads come from.
pub enum PairPads {
    /// One-time pads handed over in person (information-theoretic).
    OneTime(PadBook),
    /// A forward-secure chain seeded over the network (computational).
    Ratchet(Ratchet),
}

impl PairPads {
    fn check(&self, round: u64) -> Result<(), DcError> {
        match self {
            PairPads::OneTime(b) => b.check(round),
            PairPads::Ratchet(r) => r.check(round),
        }
    }

    fn take(&mut self, round: u64) -> Result<[u8; BODY_LEN], DcError> {
        match self {
            PairPads::OneTime(b) => b.take(round),
            PairPads::Ratchet(r) => r.take(round),
        }
    }

    /// Rounds left: a book runs out, a chain does not.
    pub fn rounds_left(&self) -> u64 {
        match self {
            PairPads::OneTime(b) => b.rounds_left(),
            PairPads::Ratchet(_) => u64::MAX,
        }
    }
}

/// One member's pads for one cell: [`PairPads`] per partner.
///
/// `books` holds the pads shared with every OTHER member, ordered by partner index with
/// the member's own index skipped (partner indices below `my_index` first).
pub struct CellPads {
    n: usize,
    books: Vec<PairPads>,
}

impl CellPads {
    /// Pads for member `my_index` of an `n`-member cell, from its n-1 books.
    ///
    /// Refuses cells outside [`MIN_CELL_SIZE`]..=[`MAX_CELL_SIZE`]: anonymity holds among
    /// the honest members H while |H| >= 2, and from four members one colluder still
    /// leaves three, who keep every pad of theirs secret.
    pub fn new(n: usize, my_index: usize, books: Vec<PairPads>) -> Result<Self, DcError> {
        if !(MIN_CELL_SIZE..=MAX_CELL_SIZE).contains(&n) || my_index >= n || books.len() != n - 1 {
            return Err(DcError::BadPads);
        }
        Ok(Self { n, books })
    }

    /// Cell size.
    pub fn n(&self) -> usize {
        self.n
    }

    /// Rounds left before the first book runs out.
    pub fn rounds_left(&self) -> u64 {
        self.books
            .iter()
            .map(PairPads::rounds_left)
            .min()
            .unwrap_or(0)
    }

    /// This member's 64-byte body for the round, consuming the round's pad from every
    /// book. `event = None` is the silent (null) contribution: still a full pad XOR,
    /// never zeros. Checks every book first, so a refused round consumes nothing.
    pub fn body(&mut self, round: u64, event: Option<&DcEvent>) -> Result<[u8; BODY_LEN], DcError> {
        for book in &self.books {
            book.check(round)?;
        }
        let mut b = [0u8; BODY_LEN];
        for book in &mut self.books {
            let pad = book.take(round)?;
            for (x, p) in b.iter_mut().zip(pad.iter()) {
                *x ^= p;
            }
        }
        if let Some(ev) = event {
            let enc = ev.encode();
            for (x, e) in b.iter_mut().zip(enc.iter()) {
                *x ^= e;
            }
        }
        Ok(b)
    }

    /// Full frame for the round (MAC zeroed; the integration layer calls
    /// `Frame::seal` with the per-epoch anonymous MAC key).
    pub fn transmit(
        &mut self,
        cell_id: u32,
        round: u64,
        event: Option<&DcEvent>,
    ) -> Result<Frame, DcError> {
        Ok(Frame::build(cell_id, round, self.body(round, event)?))
    }
}

/// One member's broadcast frame. Fixed 111 bytes.
#[derive(Debug, Clone)]
pub struct Frame {
    /// The frame on the wire.
    pub bytes: [u8; FRAME_LEN],
}

impl Frame {
    /// Frame a body for (cell, round); the MAC stays zero until [`Frame::seal`].
    pub fn build(cell_id: u32, round: u64, body: [u8; BODY_LEN]) -> Self {
        let mut b = [0u8; FRAME_LEN];
        b[0..2].copy_from_slice(&MAGIC.to_be_bytes());
        b[2..6].copy_from_slice(&cell_id.to_be_bytes());
        b[6..14].copy_from_slice(&round.to_be_bytes());
        b[14] = 0; // flags: constant in v2. MUST NOT encode sender state.
        b[HEADER_LEN..HEADER_LEN + BODY_LEN].copy_from_slice(&body);
        // bytes[79..111]: member_mac, zero until seal()
        Frame { bytes: b }
    }

    /// The frame magic.
    pub fn magic(&self) -> u16 {
        u16::from_be_bytes([self.bytes[0], self.bytes[1]])
    }

    /// The cell this frame belongs to.
    pub fn cell_id(&self) -> u32 {
        let mut b = [0u8; 4];
        b.copy_from_slice(&self.bytes[2..6]);
        u32::from_be_bytes(b)
    }

    /// The round this frame belongs to.
    pub fn round(&self) -> u64 {
        let mut b = [0u8; 8];
        b.copy_from_slice(&self.bytes[6..14]);
        u64::from_be_bytes(b)
    }

    /// The member's 64-byte body.
    pub fn body(&self) -> [u8; BODY_LEN] {
        let mut b = [0u8; BODY_LEN];
        b.copy_from_slice(&self.bytes[HEADER_LEN..HEADER_LEN + BODY_LEN]);
        b
    }

    /// HMAC-SHA256 over the frame prefix under the per-epoch anonymous MAC
    /// key. The key is registered blinded with the directory (blind-RSA
    /// credits machinery) so verification does not identify the member.
    pub fn seal(&mut self, mac_key: &[u8; 32]) {
        let mut m = Hmac::<Sha256>::new_from_slice(mac_key).expect("hmac accepts any key length");
        m.update(&self.bytes[..HEADER_LEN + BODY_LEN]);
        let tag = m.finalize().into_bytes();
        self.bytes[HEADER_LEN + BODY_LEN..FRAME_LEN].copy_from_slice(&tag);
    }

    /// True when the MAC verifies under `mac_key` (cell membership, never member identity).
    pub fn verify(&self, mac_key: &[u8; 32]) -> bool {
        let mut m = Hmac::<Sha256>::new_from_slice(mac_key).expect("hmac accepts any key length");
        m.update(&self.bytes[..HEADER_LEN + BODY_LEN]);
        m.verify_slice(&self.bytes[HEADER_LEN + BODY_LEN..FRAME_LEN])
            .is_ok()
    }
}

/// XOR-aggregate all bodies of one (cell, round) and decode.
///
/// All frames must agree on cell and round; a mixed-round input is an
/// error (the caller aborts the round — design doc §1.2), not `Garbled`,
/// because it indicates a protocol violation rather than a jam.
pub fn group_sum(frames: &[Frame]) -> Result<DcOutcome, DcError> {
    if frames.is_empty() {
        return Err(DcError::NoFrames);
    }
    let cell = frames[0].cell_id();
    let round = frames[0].round();
    for f in frames {
        if f.magic() != MAGIC {
            return Err(DcError::BadMagic);
        }
        if f.cell_id() != cell || f.round() != round {
            return Err(DcError::RoundMismatch);
        }
    }
    let mut sum = [0u8; BODY_LEN];
    for f in frames {
        let b = f.body();
        for (s, x) in sum.iter_mut().zip(b.iter()) {
            *s ^= x;
        }
    }
    Ok(DcEvent::decode(&sum))
}

