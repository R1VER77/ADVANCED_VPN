    #[test]
    fn a_pad_is_handed_out_once_and_then_wiped() {
        let mut b = PadBook::new(VEC_FIRST_ROUND, book_bytes("vec-book", 0, 1)).unwrap();
        assert_eq!(b.rounds_left(), VEC_BOOK_ROUNDS);
        let p = b.take(VEC_ROUND).unwrap();
        assert_ne!(p, [0u8; BODY_LEN]);
        // Never twice, never an earlier (skipped) round, never before the book.
        assert_eq!(b.take(VEC_ROUND), Err(DcError::PadUsed));
        assert_eq!(b.take(VEC_ROUND - 1), Err(DcError::PadUsed));
        assert_eq!(b.take(VEC_FIRST_ROUND - 1), Err(DcError::PadUsed));
        // The used pad and the skipped ones are zero in memory; later ones are intact.
        let used = ((VEC_ROUND - VEC_FIRST_ROUND + 1) as usize) * BODY_LEN;
        assert!(b.pads[..used].iter().all(|&x| x == 0));
        assert_eq!(b.pads[used..], book_bytes("vec-book", 0, 1)[used..]);
        assert_eq!(
            b.rounds_left(),
            VEC_FIRST_ROUND + VEC_BOOK_ROUNDS - VEC_ROUND - 1
        );
    }

