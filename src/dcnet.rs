    #[test]
    fn frame_mac_roundtrip() {
        let m = CellPads::new(4, 2, vec_k(4, 2)).unwrap();
        let mut f = m.transmit(VEC_CELL_ID, VEC_ROUND, Some(&test_event()));
        let key = [7u8; 32];
        f.seal(&key);
        assert!(f.verify(&key));
        let mut bad_key = [8u8; 32];
        assert!(!f.verify(&bad_key));
        bad_key[0] = 6;
        assert!(!f.verify(&bad_key));
        // tamper one body bit -> MAC fails
        let mut tampered = f.clone();
        tampered.bytes[20] ^= 1;
        assert!(!tampered.verify(&key));
    }

    #[test]
    fn group_sum_rejects_mixed_rounds_and_bad_magic() {
        let members: Vec<CellPads> = (0..4)
            .map(|i| CellPads::new(4, i, vec_k(4, i)).unwrap())
            .collect();
        let ev = test_event();
        let frames: Vec<Frame> = members
            .iter()
            .enumerate()
            .map(|(i, m)| {
                m.transmit(
                    VEC_CELL_ID,
                    VEC_ROUND,
                    if i == 2 { Some(&ev) } else { None },
                )
            })
            .collect();
        match group_sum(&frames) {
            Ok(DcOutcome::Event(e)) => assert_eq!(e, ev),
            other => panic!("expected event, got {:?}", other),
        }

        // mixed rounds -> protocol error, caller aborts the round
        let stale_frame = members[0].transmit(VEC_CELL_ID, VEC_ROUND - 1, None);
        let mut mixed = frames.clone();
        mixed[0] = stale_frame;
        assert_eq!(group_sum(&mixed), Err(DcError::RoundMismatch));

        // bad magic -> rejected
        let mut bad = frames.clone();
        bad[1].bytes[0] = 0xDE;
        assert_eq!(group_sum(&bad), Err(DcError::BadMagic));

        assert_eq!(group_sum(&[]), Err(DcError::NoFrames));
    }

    #[test]
    fn silent_body_is_never_zero_and_looks_random() {
        // a silent member's body is a pad XOR, never all-zero — otherwise
        // the sender would be identifiable by elimination
        let m = CellPads::new(12, 5, (0..11).map(|i| [i as u8; 32]).collect()).unwrap();
        let b = m.body(0x0BAD_C0DE, 1234, None);
        assert!(!b.iter().all(|&x| x == 0));
        // and no 32-byte-aligned structure leaks (rough uniformity smoke
        // test: byte values cover a sane range)
        let distinct = b.iter().fold(0u32, |acc, &x| acc | (1u32 << (x % 32)));
        assert!(distinct.count_ones() >= 24);
    }

