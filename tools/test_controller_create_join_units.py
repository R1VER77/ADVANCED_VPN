class CheckTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.where = paths(self.root)
        self.ctx = dict(vault=self.where["vault"], exit=self.where["exit"])

    def test_operator_key_absent_waits_for_the_user(self):
        result = check_operator(self.ctx)
        self.assertEqual(result.state, "waiting_for_user")

    def test_a_real_kem_unlock_key_passes(self):
        fixture = OperatorUnlockFixture(self.where["vault"])
        result = check_operator(self.ctx)
        self.assertEqual(result.state, "complete")
        self.assertEqual(result.evidence["unlock_sha256"], hashlib.sha256(fixture.public).hexdigest())

    def test_a_wrong_length_unlock_key_blocks(self):
        vault = self.where["vault"]
        vault.mkdir(parents=True)
        (vault / OPERATOR_UNLOCK).write_bytes(b"short")
        (vault / OPERATOR_UNLOCK).chmod(0o600)
        self.assertEqual(check_operator(self.ctx).state, "blocked")

    def test_the_exit_request_completes_both_checks(self):
        fixture = OperatorUnlockFixture(self.where["vault"])
        write_exit_request(self.where["exit"], fixture.public)
        self.assertEqual(check_operator(self.ctx).state, "complete")
        result = check_exit(self.ctx)
        self.assertEqual(result.state, "complete")
        self.assertEqual(result.evidence["protection"], "operator")

    def test_an_exit_request_bound_to_another_operator_blocks(self):
        OperatorUnlockFixture(self.where["vault"])  # this operator's key, in the vault
        other = OperatorUnlockFixture(self.root / "other-vault")
        write_exit_request(self.where["exit"], other.public)
        self.assertEqual(check_exit(self.ctx).state, "blocked")

    def test_a_non_exit_role_request_blocks(self):
        fixture = OperatorUnlockFixture(self.where["vault"])
        write_exit_request(self.where["exit"], fixture.public, role="relay")
        self.assertEqual(check_exit(self.ctx).state, "blocked")

    def test_a_missing_exit_request_waits_for_the_user(self):
        self.assertEqual(check_exit(self.ctx).state, "waiting_for_user")

    def test_the_two_new_checks_run_under_the_real_engine(self):
        fixture = OperatorUnlockFixture(self.where["vault"])
        write_exit_request(self.where["exit"], fixture.public)
        out = setup_flow.run(
            [
                Step("operator", "operator", (), check_operator),
                Step("exit", "exit", ("operator",), check_exit),
            ],
            self.ctx,
            self.root / "engine",
        )
        self.assertEqual([r.state for _, r in out], ["complete", "complete"])


class ValidateTests(unittest.TestCase):
    def test_the_operator_actions_are_create_branch_only_and_take_no_arguments(self):
        self.assertEqual(validate("create", "create_operator_keys", None), {})
        self.assertEqual(validate("create", "request_exit", None), {})
        for name in ("create_operator_keys", "request_exit", "sign_route"):
            with self.assertRaises(Refused):
                validate("join", name, None)
        with self.assertRaises(Refused):
            validate("create", "create_operator_keys", {"sneak": 1})

    def test_sign_route_happy_path_and_hop_rules(self):
        good = dict(
            hops=2,
            exit="203.0.113.7:443",
            relay="203.0.113.8:443",
            allowance_gib=500,
            extra_requests=[dict(role="relay", name="relay-a")],
        )
        fields = validate("create", "sign_route", good)
        self.assertEqual(fields["hops"], 2)
        self.assertEqual(fields["extra_requests"], [("relay", "relay-a")])
        for bad in (
            dict(hops=2, exit="x", relay="y", allowance_gib=10, extra_requests=[]),  # no relay request
            dict(
                hops=3, exit="x", relay="y", middle="z", allowance_gib=10, extra_requests=[dict(role="relay", name="r")]
            ),  # no middle request
            dict(hops=1, exit="x", relay="y", allowance_gib=10, extra_requests=[]),  # 1-hop has no relay
            dict(
                hops=2, exit="x", relay="y", allowance_gib=10, extra_requests=[dict(role="relay", name="../escape")]
            ),  # traversal
            dict(
                hops=2, exit="x; rm -rf /", relay="y", allowance_gib=10, extra_requests=[dict(role="relay", name="r")]
            ),  # endpoint charset
            dict(
                hops=2, exit="x", relay="y", allowance_gib="500", extra_requests=[dict(role="relay", name="r")]
            ),  # allowance type
            dict(
                hops=2, exit="x", relay="y", allowance_gib=0, extra_requests=[dict(role="relay", name="r")]
            ),  # allowance range
            dict(
                hops=4, exit="x", relay="y", allowance_gib=10, extra_requests=[dict(role="relay", name="r")]
            ),  # the 3-hop ceiling
            dict(
                hops=2,
                exit="x",
                relay="y",
                allowance_gib=10,
                cover_name="bad name",
                extra_requests=[dict(role="relay", name="r")],
            ),  # cover charset
        ):
            with self.subTest(bad=bad):
                with self.assertRaises(Refused):
                    validate("create", "sign_route", bad)

    def test_unknown_actions_and_branches_are_refused(self):
        with self.assertRaises(Refused):
            validate("create", "launch_missiles", None)
        with self.assertRaises(Refused):
            validate("sideways", "sign_route", {})


class PreviewApplyTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.where = paths(self.root)
        self.fixture = OperatorUnlockFixture(self.where["vault"])
        # the wizard's own request files exist
        state = self.where["state"]
        state.mkdir(parents=True, exist_ok=True)
        (state / "device.req").write_bytes(b"client public request")
        (self.where["exit"] / "device.req").parent.mkdir(parents=True, exist_ok=True)
        (self.where["exit"] / "device.req").write_bytes(b"exit public request")

    def test_preview_and_spec_for_the_operator_keys(self):
        preview = prepare("create", "create_operator_keys", None, self.where)
        self.assertEqual(preview["schema"], SCHEMA)
        self.assertLessEqual(len(preview["effects"]), 12)
        spec = apply("create", "create_operator_keys", None, self.where)
        self.assertEqual(spec["kind"], "dispatch")
        self.assertEqual(spec["argv"], ["unlock-key", "--vault", str(self.where["vault"])])

    def test_request_exit_refused_until_the_operator_key_exists(self):
        empty = paths(self.root / "elsewhere")
        with self.assertRaises(Refused):
            prepare("create", "request_exit", None, empty)
        with self.assertRaises(Refused):
            apply("create", "request_exit", None, empty)

    def test_request_exit_spec_is_the_exact_hardcoded_argv(self):
        spec = apply("create", "request_exit", None, self.where)
        self.assertEqual(spec["kind"], "dispatch")
        self.assertEqual(spec["state"], str(self.where["exit"]))
        self.assertEqual(
            spec["argv"],
            [
                "request",
                "--role",
                "exit",
                "--protect",
                "operator",
                "--unlock-key",
                str(self.where["vault"] / OPERATOR_UNLOCK),
                "--out",
                str(self.where["exit"] / "device.req"),
            ],
        )

    def test_sign_route_spec_always_states_an_allowance_never_accept_cost(self):
        request = dict(hops=1, exit="198.51.100.4:443", allowance_gib=250)
        preview = prepare("create", "sign_route", request, self.where)
        self.assertIn("250 GiB", " ".join(preview["effects"]))
        spec = apply("create", "sign_route", request, self.where)
        self.assertEqual(spec["kind"], "dispatch")
        self.assertIn("--allowance-gib", spec["argv"])
        self.assertNotIn("--accept-cost", spec["argv"])
        self.assertIn(f"client={self.where['state'] / 'device.req'}", spec["argv"])
        self.assertIn(f"exit={self.where['exit'] / 'device.req'}", spec["argv"])

    def test_sign_route_refuses_when_a_wizard_request_is_missing(self):
        (self.where["state"] / "device.req").unlink()
        request = dict(hops=1, exit="198.51.100.4:443", allowance_gib=250)
        with self.assertRaises(Refused):
            prepare("create", "sign_route", request, self.where)
        with self.assertRaises(Refused):
            apply("create", "sign_route", request, self.where)

    def test_the_new_actions_are_not_the_backends_existing_ones(self):
        self.assertIsNone(prepare("join", "connect", {}, self.where))
        self.assertIsNone(prepare("create", "request_device", {}, self.where))


class JournalTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.path = self.root / "journal" / JOURNAL_NAME

    def test_entries_are_digests_never_content(self):
        request = dict(bundle_base64="c2VjcmV0IHNlY3JldCBzZWNyZXQ=", replace=False)
        entry = journal_append(self.path, "join", "import_bundle", request, uid=1000, now=1.5)
        self.assertEqual(entry["uid"], 1000)
        line = self.path.read_text()
        self.assertIn(entry["input_digest"], line)
        self.assertNotIn("c2VjcmV0", line)
        self.assertEqual(self.path.stat().st_mode & 0o077, 0)

    def test_the_journal_rotates_at_the_cap_keeping_one_generation(self):
        for i in range(JOURNAL_MAX_ENTRIES + 1):
            journal_append(self.path, "create", "request_exit", None, uid=0, now=float(i))
        rotated = self.path.with_name(JOURNAL_NAME + ".1")
        self.assertTrue(rotated.exists())
        self.assertEqual(len(rotated.read_text().splitlines()), JOURNAL_MAX_ENTRIES)
        self.assertEqual(len(self.path.read_text().splitlines()), 1)

    def test_a_journal_with_open_permissions_is_refused(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.path.write_text("x\n")
        self.path.chmod(0o644)
        with self.assertRaises(Refused):
            journal_append(self.path, "create", "request_exit", None, uid=0)


class DecorateTests(unittest.TestCase):
    def report(self, current, **states):
        return dict(
            schema=SCHEMA,
            complete=sum(v in ("complete", "skipped") for v in states.values()),
            total=len(states),
            current=current,
            finished=False,
            steps=[dict(id=k, title=k, state=v, say="", actions=[]) for k, v in states.items()],
        )

    def test_join_offers_only_the_client_actions(self):
        report = self.report(
            "profile",
            host="complete",
            key="complete",
            vault="complete",
            profile="waiting_for_user",
            servers="pending",
            guard="pending",
            protected="pending",
        )
        decorate_report("join", report, Path("/tmp/state"))
        offered = {a["action"] for s in report["steps"] for a in s["actions"]}
        self.assertEqual(offered, {"request_device"})

    def test_create_offers_the_three_new_actions_at_their_steps(self):
        report = self.report(
            "operator",
            host="complete",
            key="complete",
            vault="complete",
            operator="waiting_for_user",
            exit="pending",
            profile="pending",
            servers="pending",
            guard="pending",
            protected="pending",
        )
        decorate_report("create", report, Path("/tmp/state"))
        by_id = {s["id"]: s for s in report["steps"]}
        self.assertEqual([a["action"] for a in by_id["operator"]["actions"]], ["create_operator_keys"])
        self.assertEqual(by_id["exit"]["actions"], [])  # pending: not reachable yet
        report2 = self.report(
            "exit",
            host="complete",
            key="complete",
            vault="complete",
            operator="complete",
            exit="waiting_for_user",
            profile="pending",
            servers="pending",
            guard="pending",
            protected="pending",
        )
        decorate_report("create", report2, Path("/tmp/state"))
        by_id = {s["id"]: s for s in report2["steps"]}
        self.assertEqual([a["action"] for a in by_id["exit"]["actions"]], ["request_exit"])

    def test_complete_steps_offer_nothing_and_connect_only_at_the_current_step(self):
        report = self.report(
            "guard",
            host="complete",
            key="complete",
            vault="complete",
            operator="complete",
            exit="complete",
            profile="complete",
            servers="complete",
            guard="waiting_for_user",
            protected="pending",
        )
        decorate_report("create", report, Path("/tmp/state"))
        by_id = {s["id"]: s for s in report["steps"]}
        self.assertEqual(by_id["guard"]["actions"], [dict(action="connect", scope="applications")])
        self.assertEqual(by_id["protected"]["actions"], [])
        for step in report["steps"]:
            if step["state"] in ("complete", "skipped"):
                self.assertEqual(step["actions"], [])


# The full writer path needs mlkem + mldsa (the operator-protected request
# seals the server's data key to the hybrid unlock key and signs with
# ML-DSA). It runs on the hash-locked environment; this sandbox's
# cryptography build lacks both, so it is skipped here and the checks are
# tested against the writer's exact canonical shape above instead.
@unittest.skipUnless(_pq_crypto_available(), "mlkem/mldsa need the hash-locked environment")
class RealWriterTests(unittest.TestCase):
    def test_the_real_managed_profile_request_passes_both_checks(self):
        import tempfile

        import managed_profile as mp
        from keyguard import kem_keypair

        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            where = paths(root)
            where["vault"].mkdir(mode=0o700, parents=True)
            _private, public = kem_keypair()
            (where["vault"] / OPERATOR_UNLOCK).write_bytes(public)
            (where["vault"] / OPERATOR_UNLOCK).chmod(0o600)
            mp.request("exit", where["exit"], "operator", unlock_public=public)
            ctx = dict(vault=where["vault"], exit=where["exit"])
            self.assertEqual(check_operator(ctx).state, "complete")
            self.assertEqual(check_exit(ctx).state, "complete")


class FieldHardeningTests(unittest.TestCase):
    """GUI fields reach a root command line: a flag-shaped or path-shaped value is refused
    here, not left for the command's own parser to reject (found while merging, 21 Nov)."""

    def ask(self, **kw):
        req = dict(hops=2, exit="198.51.100.2:4444", relay="198.51.100.1:443", allowance_gib=5,
                   extra_requests=[dict(role="relay", name="relay.req")])  # fmt: skip
        req.update(kw)
        return validate("create", "sign_route", req)

    def test_flag_shaped_endpoints_are_refused(self):
        for bad in ("--accept-cost", "-1", "--exit", "198.51.100.2", "0.0.0.0:443", "198.51.100.2:0"):
            with self.subTest(bad=bad), self.assertRaises(Refused):
                self.ask(exit=bad)
        with self.assertRaises(Refused):
            self.ask(relay="--accept-cost")

    def test_the_first_hop_is_ipv4_and_a_later_hop_may_be_ipv6(self):
        self.assertEqual(self.ask(exit="[2001:db8::4]:4444")["exit"], "[2001:db8::4]:4444")
        with self.assertRaises(Refused):
            self.ask(relay="[2001:db8::1]:443")
        with self.assertRaises(Refused):
            validate("create", "sign_route", dict(hops=1, exit="[2001:db8::4]:4444", allowance_gib=5))

    def test_names_never_start_with_a_dash_or_a_dot(self):
        for bad in ("-x", ".", "..", ".hidden"):
            with self.subTest(bad=bad), self.assertRaises(Refused):
                self.ask(extra_requests=[dict(role="relay", name=bad)])
        for bad in ("-cover", ".cover"):
            with self.subTest(bad=bad), self.assertRaises(Refused):
                self.ask(cover_name=bad)
        self.assertEqual(self.ask(cover_name="cdn.example.org")["cover_name"], "cdn.example.org")


