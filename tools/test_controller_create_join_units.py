class OperatorUnlockFixture:
    """An unlock public key of exactly the hybrid length keyguard.KEM_PUBLIC
    (X25519 + ML-KEM-768). The X25519 half is real; in environments whose
    cryptography build has mlkem the whole pair is generated by keyguard's
    own kem_keypair, and the gated test at the bottom exercises the full
    managed_profile writer. Here the PQ half is random filler of exactly
    the right length: the checks under test verify presence, length and
    the SHA-256 binding, all of which are real."""

    def __init__(self, vault: Path):
        from cryptography.hazmat.primitives import serialization
        from cryptography.hazmat.primitives.asymmetric import x25519

        self.vault = vault
        vault.mkdir(mode=0o700, parents=True, exist_ok=True)
        try:
            from keyguard import kem_keypair

            self.private, self.public = kem_keypair()
        except ImportError:  # this sandbox's cryptography has no mlkem
            a = x25519.X25519PrivateKey.generate()
            self.private = None
            self.public = a.public_key().public_bytes(
                serialization.Encoding.Raw, serialization.PublicFormat.Raw
            ) + os.urandom(KEM_PUBLIC_LEN - 32)
        path = vault / OPERATOR_UNLOCK
        path.write_bytes(self.public)
        path.chmod(0o600)


def write_exit_request(directory: Path, unlock_public: bytes, role: str = "exit"):
    """Write request.json in the exact canonical shape managed_profile's
    writer produces for an operator-protected server (role and the unlock
    record with the sha256 binding to the operator's public key)."""
    directory.mkdir(mode=0o700, parents=True, exist_ok=True)
    request = dict(
        schema=1,
        role=role,
        unlock=dict(
            schema=1,
            operator_unlock_sha256=hashlib.sha256(unlock_public).hexdigest(),
            wrapped=dict(schema=1, ephemeral="", mlkem="", nonce="", ciphertext=""),
        ),
    )
    path = directory / "request.json"
    path.write_text(json.dumps(request, sort_keys=True))
    path.chmod(0o600)
    return request


