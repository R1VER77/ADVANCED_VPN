/// A mix's published keys (gossip descriptor).
#[derive(Clone, Debug)]
pub struct MixKeys {
    pub id: [u8; 16],
    pub mlkem_ek: Vec<u8>,
    pub x25519_pk: [u8; 32],
}

/// A mix's secret keys (held only by the mix).
#[derive(Clone, Debug)]
pub struct MixSecret {
    pub mlkem_dk: Vec<u8>,
    pub x25519_sk: [u8; 32],
}

/// Mix keypair from entropy (SWAPPABLE: platform CSPRNG in production).
pub fn mix_keypair(
    d: &[u8; 32],
    z: &[u8; 32],
    x25519_sk: [u8; 32],
    id: [u8; 16],
) -> (MixKeys, MixSecret) {
    let (ek, dk) = crypto::mlkem_keygen(d, z);
    (
        MixKeys {
            id,
            mlkem_ek: ek,
            x25519_pk: crypto::x25519_base(&x25519_sk),
        },
        MixSecret {
            mlkem_dk: dk,
            x25519_sk,
        },
    )
}

// ---------------------------------------------------------------------------
// RNG (SWAPPABLE marker: replace DetRng with the platform CSPRNG)
// ---------------------------------------------------------------------------

pub trait SphinxRng {
    fn fill(&mut self, buf: &mut [u8]);
}

/// INSECURE splitmix64 RNG for tests and vector generation only.
pub struct DetRng(pub u64);

impl SphinxRng for DetRng {
    fn fill(&mut self, buf: &mut [u8]) {
        for chunk in buf.chunks_mut(8) {
            self.0 = self.0.wrapping_add(0x9E37_79B9_7F4A_7C15);
            let mut z = self.0;
            z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
            z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
            z ^= z >> 31;
            for (b, x) in chunk.iter_mut().zip(z.to_le_bytes()) {
                *b = x;
            }
        }
    }
}

// ---------------------------------------------------------------------------
// Key schedule (§2.6)
// ---------------------------------------------------------------------------

fn ks(key_material: &[u8], domain: &str, index: u8, len: usize) -> Vec<u8> {
    crypto::hkdf_sha256(domain.as_bytes(), key_material, &[index], len)
}

fn hop_mac_key(k: &[u8; 32], i: usize) -> [u8; 32] {
    ks(k, "avpn/pq-sphinx/mac/v1", i as u8, 32)
        .try_into()
        .unwrap()
}

fn routing_key(k: &[u8; 32], i: usize) -> [u8; 32] {
    ks(k, "avpn/pq-sphinx/rt/v1", i as u8, 32)
        .try_into()
        .unwrap()
}

fn shift_stream(k: &[u8; 32], i: usize, v: usize) -> Vec<u8> {
    let key: [u8; 32] = ks(k, "avpn/pq-sphinx/shift/v1", i as u8, 32)
        .try_into()
        .unwrap();
    crypto::chacha20_keystream(&key, &[0u8; 12], SLOTI_LEN * (v - i))
}

fn reblind_pad(k1: &[u8; 32]) -> [u8; 32] {
    ks(k1, "avpn/pq-sphinx/pad/v1", 2, 32).try_into().unwrap()
}

fn cover_stream(k: &[u8; 32], i: usize, slot_len: usize) -> Vec<u8> {
    let key: [u8; 32] = ks(k, "avpn/pq-sphinx/cover/v1", i as u8, 32)
        .try_into()
        .unwrap();
    crypto::chacha20_keystream(&key, &[0u8; 12], slot_len)
}

/// R3 — per-hop payload re-masking stream (the Sphinx β-layer):
/// `payload_mask(i) = ChaCha20(HKDF(K_i, "pmask"||i))` over the payload
/// region. The client pre-masks the sealed payload with ALL v streams;
/// each hop XORs off its own. Result: the payload bytes differ on every
/// link of the path (colluding observers cannot byte-match across an
/// honest hop), while the mailbox receives the unmasked AEAD text.
fn pmask_stream(k: &[u8; 32], i: usize, v: usize) -> Vec<u8> {
    let key: [u8; 32] = ks(k, "avpn/pq-sphinx/pmask/v1", i as u8, 32)
        .try_into()
        .unwrap();
    crypto::chacha20_keystream(&key, &[0u8; 12], CELL_SIZE - header_len(v))
}

/// R4 — dead-prefix re-randomization: hop i XORs a fresh stream over the
/// region of slots 1..i-1 (consumed at earlier hops). Without this, the
/// cover bytes written by hop 1 ride unchanged on every later link, and
/// two colluding observers could byte-match the cell across an honest
/// intermediate hop. No MAC covers the dead prefix, so this is
/// transparent to all verification. Found by the GPA-lab linkability
/// check (tests/lab.rs).
fn dead_stream(k: &[u8; 32], i: usize) -> Vec<u8> {
    let key: [u8; 32] = ks(k, "avpn/pq-sphinx/dead/v1", i as u8, 32)
        .try_into()
        .unwrap();
    let len = slot_offset(i) - FIXED_LEN;
    if len == 0 {
        Vec::new()
    } else {
        crypto::chacha20_keystream(&key, &[0u8; 12], len)
    }
}

/// §2.6: payload key mixes every hop's secret.
pub fn payload_key(secrets: &[[u8; 32]]) -> [u8; 32] {
    let mut ikm = Vec::with_capacity(32 * secrets.len());
    for s in secrets {
        ikm.extend_from_slice(s);
    }
    crypto::hkdf_sha256(b"avpn/pq-sphinx/payload/v1", &ikm, b"payload", 32)
        .try_into()
        .unwrap()
}

// ---------------------------------------------------------------------------
// Layout helpers
// ---------------------------------------------------------------------------

fn slot_offset(i: usize) -> usize {
    if i == 1 {
        FIXED_LEN
    } else {
        FIXED_LEN + SLOT1_LEN + (i - 2) * SLOTI_LEN
    }
}

fn slot_len(i: usize) -> usize {
    if i == 1 {
        SLOT1_LEN
    } else {
        SLOTI_LEN
    }
}

fn mac_field(i: usize) -> usize {
    slot_offset(i) + if i == 1 { MLKEM_CT_LEN } else { ELEM_LEN }
}

fn rt_field(i: usize) -> usize {
    mac_field(i) + MAC_LEN
}

#[derive(Debug, PartialEq, Eq)]
pub enum SphinxError {
    NotACell,
    BadVersion,
    BadHopCount,
    PayloadTooLarge,
    NotMine,
    OpenFailed,
    BadKeyLength,
}

fn parse_fixed(cell: &[u8]) -> Result<usize, SphinxError> {
    if cell.len() != CELL_SIZE {
        return Err(SphinxError::NotACell);
    }
    if cell[0] != VERSION {
        return Err(SphinxError::BadVersion);
    }
    let v = cell[1] as usize;
    if !(MIN_HOPS..=MAX_HOPS).contains(&v) {
        return Err(SphinxError::BadHopCount);
    }
    Ok(v)
}

// ---------------------------------------------------------------------------
// Routing blocks
// ---------------------------------------------------------------------------

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RoutingBlock {
    pub next_id: [u8; 16],
    pub transport_hint: [u8; 8],
    pub commands: u64,
}

fn rt_xor(key: &[u8; 32], field: &[u8]) -> [u8; RT_LEN] {
    let stream = crypto::chacha20_keystream(key, &[0u8; 12], RT_LEN);
    let mut out = [0u8; RT_LEN];
    for i in 0..RT_LEN {
        out[i] = field[i] ^ stream[i];
    }
    out
}

impl RoutingBlock {
    fn from_plain(plain: &[u8; RT_LEN]) -> Self {
        let mut next_id = [0u8; 16];
        next_id.copy_from_slice(&plain[..16]);
        let mut transport_hint = [0u8; 8];
        transport_hint.copy_from_slice(&plain[16..24]);
        let commands = u64::from_le_bytes(plain[24..32].try_into().unwrap());
        RoutingBlock {
            next_id,
            transport_hint,
            commands,
        }
    }

    fn to_plain(&self) -> [u8; RT_LEN] {
        let mut out = [0u8; RT_LEN];
        out[..16].copy_from_slice(&self.next_id);
        out[16..24].copy_from_slice(&self.transport_hint);
        out[24..32].copy_from_slice(&self.commands.to_le_bytes());
        out
    }
}

// ---------------------------------------------------------------------------
// Header construction
// ---------------------------------------------------------------------------

struct HeaderIngredients {
    k_secrets: Vec<[u8; 32]>,
    header: Vec<u8>, // client-time header bytes (length header_len(v))
}

fn build_header(
    path: &[MixKeys],
    terminal: &[u8; 16],
    rng: &mut dyn SphinxRng,
) -> Result<HeaderIngredients, SphinxError> {
    let v = path.len();
    if !(MIN_HOPS..=MAX_HOPS).contains(&v) {
        return Err(SphinxError::BadHopCount);
    }
    if path[0].mlkem_ek.len() != MLKEM_EK_LEN {
        return Err(SphinxError::BadKeyLength);
    }

    // Key agreement: entry ML-KEM, inner X25519 (§2.3).
    let mut m = [0u8; 32];
    rng.fill(&mut m);
    let (k1_vec, ct1) =
        crypto::mlkem_encaps(&path[0].mlkem_ek, &m).map_err(|_| SphinxError::BadKeyLength)?;
    let k1: [u8; 32] = k1_vec.try_into().unwrap();
    let mut secrets = vec![k1];
    let mut elems = Vec::with_capacity(v - 1);
    for hop in path.iter().skip(1) {
        let mut sk = [0u8; 32];
        rng.fill(&mut sk);
        elems.push(crypto::x25519_base(&sk));
        secrets.push(crypto::x25519(&sk, &hop.x25519_pk));
    }

    // Routing-block ciphers per hop.
    let mut rt_cipher: Vec<[u8; RT_LEN]> = Vec::with_capacity(v);
    for i in 0..v {
        let block = if i + 1 < v {
            RoutingBlock {
                next_id: path[i + 1].id,
                transport_hint: [0u8; 8],
                commands: CMD_FORWARD,
            }
        } else {
            RoutingBlock {
                next_id: *terminal,
                transport_hint: [0u8; 8],
                commands: CMD_TERMINATE,
            }
        };
        let key = routing_key(&secrets[i], i + 1);
        rt_cipher.push(rt_xor(&key, &block.to_plain()));
    }

    let shifts: Vec<Vec<u8>> = (1..=v)
        .map(|i| shift_stream(&secrets[i - 1], i, v))
        .collect();
    let pad2 = reblind_pad(&secrets[0]);

    // Backward MAC computation over per-hop ingress views (R2: header only).
    // states[m-2] holds slot m's (elem[32] || mac[32] || rt[48]) at the
    // current hop's ingress; initialized clean (state at hop v).
    let mut states: Vec<[u8; SLOTI_LEN]> = Vec::with_capacity(v - 1);
    for i in 2..=v {
        let mut s = [0u8; SLOTI_LEN];
        s[..ELEM_LEN].copy_from_slice(&elems[i - 2]);
        if i == 2 {
            for (a, b) in s[..ELEM_LEN].iter_mut().zip(pad2.iter()) {
                *a ^= b;
            }
        }
        // mac placeholder filled in as M_m becomes known
        s[ELEM_LEN..ELEM_LEN + MAC_LEN].fill(0);
        s[ELEM_LEN + MAC_LEN..].copy_from_slice(&rt_cipher[i - 1]);
        states.push(s);
    }
    let mut macs = vec![[0u8; 32]; v];
    for i in (1..=v).rev() {
        // Apply S_i to downstream slots: bring them to hop-i ingress state.
        // (S_v is empty; S_i covers slots i+1..v.)
        if i < v {
            let s = &shifts[i - 1];
            for m in (i + 1)..=v {
                let base = (m - i - 1) * SLOTI_LEN;
                for idx in 0..SLOTI_LEN {
                    states[m - 2][idx] ^= s[base + idx];
                }
            }
        }
        // M_i = MAC_ki(Enc_i || states of slots i+1..v)
        let mut buf = Vec::with_capacity(RT_LEN + SLOTI_LEN * (v - i));
        buf.extend_from_slice(&rt_cipher[i - 1]);
        for m in (i + 1)..=v {
            buf.extend_from_slice(&states[m - 2]);
        }
        let key = hop_mac_key(&secrets[i - 1], i);
        macs[i - 1] = crypto::blake3_keyed(&key, &buf);
        if i >= 2 {
            states[i - 2][ELEM_LEN..ELEM_LEN + MAC_LEN].copy_from_slice(&macs[i - 1]);
        }
    }

    // Bake client-time header: slot m fields = clean ⊕ S_1..S_{m-1}
    // (slot 2's elem additionally ⊕ pad2, which stays in until hop 1).
    let hlen = header_len(v);
    let mut header = vec![0u8; hlen];
    header[0] = VERSION;
    header[1] = v as u8;
    header[2] = 0;
    header[3] = 0;
    header[FIXED_LEN..FIXED_LEN + MLKEM_CT_LEN].copy_from_slice(&ct1);
    header[mac_field(1)..mac_field(1) + MAC_LEN].copy_from_slice(&macs[0]);
    header[rt_field(1)..rt_field(1) + RT_LEN].copy_from_slice(&rt_cipher[0]);

    for i in 2..=v {
        let off = slot_offset(i);
        let mut field = [0u8; SLOTI_LEN];
        field[..ELEM_LEN].copy_from_slice(&elems[i - 2]);
        if i == 2 {
            for (a, b) in field[..ELEM_LEN].iter_mut().zip(pad2.iter()) {
                *a ^= b;
            }
        }
        field[ELEM_LEN..ELEM_LEN + MAC_LEN].copy_from_slice(&macs[i - 1]);
        field[ELEM_LEN + MAC_LEN..].copy_from_slice(&rt_cipher[i - 1]);
        for j in 1..i {
            let s = &shifts[j - 1];
            let base = (i - j - 1) * SLOTI_LEN;
            for idx in 0..SLOTI_LEN {
                field[idx] ^= s[base + idx];
            }
        }
        header[off..off + SLOTI_LEN].copy_from_slice(&field);
    }

    Ok(HeaderIngredients {
        k_secrets: secrets,
        header,
    })
}

