/// Wrap `message` for a recipient: ML-KEM-768 encapsulation to the
/// recipient's published key, then AEAD. Variable length — it rides inside
/// the fixed-size Sphinx payload region.
pub fn recipient_seal(
    message: &[u8],
    recipient_ek: &[u8],
    rng: &mut dyn SphinxRng,
) -> Result<Vec<u8>, SphinxError> {
    let mut m = [0u8; 32];
    rng.fill(&mut m);
    let (ss, ct) = crypto::mlkem_encaps(recipient_ek, &m).map_err(|_| SphinxError::BadKeyLength)?;
    let key: [u8; 32] = crypto::hkdf_sha256(b"avpn/pq-sphinx/recipient/v1", &ss, b"key", 32)
        .try_into()
        .unwrap();
    let mut nonce = [0u8; NONCE_LEN];
    rng.fill(&mut nonce);
    let sealed = seal_inner(&key, &nonce, message, 2 + message.len());
    let (seal_ct, tag) = sealed.split_at(sealed.len() - TAG_LEN);
    let mut out = Vec::with_capacity(MLKEM_CT_LEN + NONCE_LEN + seal_ct.len() + TAG_LEN);
    out.extend_from_slice(&ct);
    out.extend_from_slice(&nonce);
    out.extend_from_slice(seal_ct);
    out.extend_from_slice(tag);
    Ok(out)
}

/// Inverse of [`recipient_seal`].
pub fn recipient_open(wrapped: &[u8], recipient_dk: &[u8]) -> Option<Vec<u8>> {
    if wrapped.len() < MLKEM_CT_LEN + NONCE_LEN + 2 + TAG_LEN {
        return None;
    }
    let (ct, rest) = wrapped.split_at(MLKEM_CT_LEN);
    let (nonce, rest) = rest.split_at(NONCE_LEN);
    let ss = crypto::mlkem_decaps(recipient_dk, ct).ok()?;
    let key: [u8; 32] = crypto::hkdf_sha256(b"avpn/pq-sphinx/recipient/v1", &ss, b"key", 32)
        .try_into()
        .unwrap();
    let nonce: [u8; 12] = nonce.try_into().unwrap();
    open_inner(&key, &nonce, rest)
}

// ---------------------------------------------------------------------------
// SURBs (§2.5, with the replier-encryptable clarification — see notes)
// ---------------------------------------------------------------------------

pub struct Surb {
    /// header || reply_hint(32): hand to the correspondent.
    pub bytes: Vec<u8>,
    /// X25519 scalar for the reply hint: keep secret, used to open replies.
    pub reply_secret: [u8; 32],
    /// Hop secrets of the reply path (R3): NEVER leaves the creator. The
    /// reply's hops ADD their payload masks en route (the replier cannot
    /// pre-mask), so the creator strips all v masks after pulling the reply.
    pub path_secrets: Vec<[u8; 32]>,
}

pub const SURB_HINT_LEN: usize = 32;

/// Build a single-use reply block over `path` to `mailbox` (the creator's).
pub fn build_surb(
    path: &[MixKeys],
    mailbox: &[u8; 16],
    rng: &mut dyn SphinxRng,
) -> Result<Surb, SphinxError> {
    let ing = build_header(path, mailbox, rng)?;
    let mut es = [0u8; 32];
    rng.fill(&mut es);
    let hint = crypto::x25519_base(&es);
    let mut bytes = ing.header;
    bytes.extend_from_slice(&hint);
    Ok(Surb {
        bytes,
        reply_secret: es,
        path_secrets: ing.k_secrets,
    })
}

/// A correspondent turns a SURB plus their message into a full cell. The
/// reply payload is AEAD'd under a key derived from an ephemeral X25519
/// agreement with the SURB's embedded hint — the replier can seal without
/// knowing any Sphinx path key, and only the SURB creator can open.
pub fn surb_reply_cell(
    surb_bytes: &[u8],
    message: &[u8],
    rng: &mut dyn SphinxRng,
) -> Result<Vec<u8>, SphinxError> {
    if surb_bytes.len() < FIXED_LEN + SLOT1_LEN + SLOTI_LEN + SURB_HINT_LEN {
        return Err(SphinxError::NotACell);
    }
    let v = surb_bytes[1] as usize;
    if !(MIN_HOPS..=MAX_HOPS).contains(&v) || surb_bytes.len() != header_len(v) + SURB_HINT_LEN {
        return Err(SphinxError::BadHopCount);
    }
    let hlen = header_len(v);
    let (header, hint) = surb_bytes.split_at(hlen);
    let hint: [u8; 32] = hint.try_into().unwrap();

    let plen = payload_len(v);
    if message.len() + 2 > plen - ELEM_LEN - NONCE_LEN {
        return Err(SphinxError::PayloadTooLarge);
    }
    let mut esk = [0u8; 32];
    rng.fill(&mut esk);
    let eph_pub = crypto::x25519_base(&esk);
    let k = crypto::x25519(&esk, &hint);
    let reply_key: [u8; 32] =
        crypto::hkdf_sha256(b"avpn/pq-sphinx/surb-reply/v1", &k, b"reply", 32)
            .try_into()
            .unwrap();

    let mut nonce = [0u8; NONCE_LEN];
    rng.fill(&mut nonce);
    let sealed = seal_inner(&reply_key, &nonce, message, plen - ELEM_LEN - NONCE_LEN);
    let (ct, tag) = sealed.split_at(sealed.len() - TAG_LEN);

    let mut cell = header.to_vec();
    cell.extend_from_slice(&eph_pub);
    cell.extend_from_slice(&nonce);
    cell.extend_from_slice(ct);
    cell.extend_from_slice(tag);
    debug_assert_eq!(cell.len(), CELL_SIZE);
    Ok(cell)
}

/// The SURB creator opens a delivered reply cell: strips the v payload
/// masks the hops applied en route, then opens the reply AEAD.
pub fn open_surb_reply(
    reply_secret: &[u8; 32],
    path_secrets: &[[u8; 32]],
    cell: &[u8],
) -> Option<Vec<u8>> {
    let v = parse_fixed(cell).ok()?;
    let hlen = header_len(v);
    let plen = payload_len(v);
    if path_secrets.len() != v {
        return None;
    }
    let payload = &cell[hlen..hlen + plen];
    if payload.len() < ELEM_LEN + NONCE_LEN + 2 + TAG_LEN {
        return None;
    }
    let mut unwrapped = cell.to_vec();
    for (i, s) in path_secrets.iter().enumerate() {
        let pm = pmask_stream(s, i + 1, v);
        for (b, m) in unwrapped[hlen..].iter_mut().zip(&pm) {
            *b ^= m;
        }
    }
    let (eph, rest) = unwrapped[hlen..].split_at(ELEM_LEN);
    let (nonce, _) = rest.split_at(NONCE_LEN);
    // Ciphertext runs to the cell's trailing 16-byte tag (outside `payload`).
    let ct_and_tag = &unwrapped[hlen + ELEM_LEN + NONCE_LEN..CELL_SIZE];
    let k = crypto::x25519(reply_secret, eph.try_into().ok()?);
    let reply_key: [u8; 32] =
        crypto::hkdf_sha256(b"avpn/pq-sphinx/surb-reply/v1", &k, b"reply", 32)
            .try_into()
            .unwrap();
    let nonce: [u8; 12] = nonce.try_into().ok()?;
    open_inner(&reply_key, &nonce, ct_and_tag)
}

