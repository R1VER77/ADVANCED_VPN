#[derive(Debug, PartialEq, Eq)]
pub enum Action {
    Forward {
        next_id: [u8; 16],
        transport_hint: [u8; 8],
    },
    Deliver {
        mailbox: [u8; 16],
    },
}

fn mac_matches(key: &[u8; 32], cell: &[u8], i: usize, v: usize) -> bool {
    let start = rt_field(i);
    let end = header_len(v);
    let expected = crypto::blake3_keyed(key, &cell[start..end]);
    let off = mac_field(i);
    let mut diff = 0u8;
    for (a, b) in expected.iter().zip(&cell[off..off + MAC_LEN]) {
        diff |= a ^ b;
    }
    diff == 0
}

/// Process a cell in place. On success the buffer holds the outgoing cell
/// (consumed slot overwritten with cover bytes, downstream slots shifted).
///
/// [`SphinxError::NotMine`] covers both cells addressed elsewhere and
/// corrupted/junk cells — the mix CANNOT distinguish them, which is the
/// §1.2 failure discipline: the caller must enqueue-then-discard with the
/// same delay distribution as a healthy cell, never drop immediately.
pub fn process_cell(cell: &mut [u8], sk: &MixSecret) -> Result<Action, SphinxError> {
    let v = parse_fixed(cell)?;

    // Position discovery: try every slot (§1.9 — no position view).
    let mut position: Option<(usize, [u8; 32])> = None;
    // Candidate slot 1: ML-KEM decaps on the entry ciphertext (cover bytes
    // for later hops decapsulate to garbage; the MAC check fails).
    if sk.mlkem_dk.len() == MLKEM_DK_LEN {
        if let Ok(k1c) =
            crypto::mlkem_decaps(&sk.mlkem_dk, &cell[kem_field()..kem_field() + MLKEM_CT_LEN])
        {
            let k1c: [u8; 32] = k1c.try_into().unwrap();
            if mac_matches(&hop_mac_key(&k1c, 1), cell, 1, v) {
                position = Some((1, k1c));
            }
        }
    }
    if position.is_none() {
        for j in 2..=v {
            let mut elem = [0u8; ELEM_LEN];
            elem.copy_from_slice(&cell[slot_offset(j)..slot_offset(j) + ELEM_LEN]);
            let kj = crypto::x25519(&sk.x25519_sk, &elem);
            if mac_matches(&hop_mac_key(&kj, j), cell, j, v) {
                position = Some((j, kj));
                break;
            }
        }
    }
    let (i, k) = match position {
        Some(p) => p,
        None => return Err(SphinxError::NotMine),
    };

    // Decode this hop's routing block.
    let rkey = routing_key(&k, i);
    let rt_plain = rt_xor(&rkey, &cell[rt_field(i)..rt_field(i) + RT_LEN]);
    let block = RoutingBlock::from_plain(&rt_plain);

    // Consume slot i: cover bytes of the same length (§2.3).
    let cover = cover_stream(&k, i, slot_len(i));
    let off = slot_offset(i);
    for (b, c) in cell[off..off + slot_len(i)].iter_mut().zip(&cover) {
        *b = *c;
    }

    // Shift downstream slots (R1: full slot) with S_i.
    let s = &shifts_pub(&k, i, v);
    for m in (i + 1)..=v {
        let moff = slot_offset(m);
        let base = (m - i - 1) * SLOTI_LEN;
        for idx in 0..SLOTI_LEN {
            cell[moff + idx] ^= s[base + idx];
        }
    }

    // Entry hop removes the §2.3 re-blinding pad from slot 2's element.
    if i == 1 && v >= 2 {
        let pad2 = reblind_pad(&k);
        let off2 = slot_offset(2);
        for idx in 0..ELEM_LEN {
            cell[off2 + idx] ^= pad2[idx];
        }
    }

    // R3: remove this hop's payload mask (derived from K_i, so it is
    // computed only after the slot is found — position-independent work).
    let hlen = header_len(v);
    let pm = pmask_stream(&k, i, v);
    for (b, m) in cell[hlen..].iter_mut().zip(&pm) {
        *b ^= m;
    }

    // R4: re-randomize the dead prefix (slots 1..i-1) so consumed cover
    // bytes never appear identically on two links of the path.
    if i >= 2 {
        let ds = dead_stream(&k, i);
        for (b, d) in cell[FIXED_LEN..slot_offset(i)].iter_mut().zip(&ds) {
            *b ^= d;
        }
    }

    if block.commands & CMD_TERMINATE != 0 {
        Ok(Action::Deliver {
            mailbox: block.next_id,
        })
    } else {
        Ok(Action::Forward {
            next_id: block.next_id,
            transport_hint: block.transport_hint,
        })
    }
}

fn kem_field() -> usize {
    slot_offset(1)
}

fn shifts_pub(k: &[u8; 32], i: usize, v: usize) -> Vec<u8> {
    shift_stream(k, i, v)
}

