//! PQ-Sphinx header, option E: entry ML-KEM-768 + inner X25519 (§2).
//!
//! Wire format (MIX_LANE_DESIGN.md §2.2):
//!
//! ```text
//! fixed   := version(1) || n_hops(1) || flags(1) || reserved(1)
//! slot 1  := mlkem_ct(1088) || mac(32) || rt_block(48)      = 1168 B
//! slot i  := elem(32) || mac(32) || rt_block(48)            = 112 B (i >= 2)
//! header_len(v) = 4 + 1168 + (v-1)*112        (v=3: 1396, +112 per hop)
//! cell    := header || payload(P) || aead_tag(16)
//! ```
//!
//! Two refinements over the design doc, both forced by implementability and
//! documented in IMPLEMENTATION_NOTES.md:
//!
//! **R1 — full-slot shifting.** §2.2 says hop i re-encrypts the *routing
//! blocks* of downstream slots. That alone leaves downstream MAC fields as
//! static bytes from client to their hop — a passive observer comparing the
//! entry link with a later link could match them and link the cell. The
//! shift keystream therefore covers the entire downstream slot (element +
//! MAC + routing block).
//!
//! **R2 — MAC covers the header suffix only.** §2.2/§1.2 say the per-hop
//! MAC covers "header suffix + payload", but §1.7's anti-tagging story
//! ("a tagged cell survives to the mailbox and fails client-side
//! decryption") and §2.5's SURBs both require mixes NOT to authenticate the
//! payload: a SURB holder cannot compute MACs over a reply payload they
//! choose. MAC_i therefore covers slot i's routing-block field plus all
//! downstream slots, stopping at the header boundary. Payload integrity is
//! end-to-end via the AEAD under `payload_key`.
//!
//! Position hiding (§1.9): every mix attempts every slot — one ML-KEM
//! decaps plus v−1 X25519 shared secrets and MAC checks — and exactly one
//! slot verifies. Consumed slots are overwritten with same-length cover
//! bytes, so wire size and per-cell work are position-independent.
//!
//! This is the PRODUCTION port of the reference crate (`pq_sphinx_pack`):
//! identical protocol logic, primitives swapped to audited crates via
//! [`crate::crypto`] — ml-kem (RustCrypto, FIPS 203), x25519-dalek,
//! chacha20poly1305, blake3, sha2, hkdf. Byte-identity with the reference
//! is enforced by `tests/cells.rs` (full-cell vectors) and `tests/vectors.rs`
//! (primitive vectors), both generated by the cross-verified reference
//! crate and Python (kyber-py / cryptography / blake3).
//!
//! §2.3 XOR re-blinding: `pad_2 = HKDF(K_1, "pad"||2)` blinds hop 2's
//! element with the PQ entry secret; hop 1 removes it while peeling.
//! REVIEW-PENDING, exactly as flagged in the design doc — see
//! `tamarin/REBLINDING_PLAN.md`.

use crate::crypto;

pub const VERSION: u8 = 1;
pub const MAX_HOPS: usize = 5;
pub const MIN_HOPS: usize = 2;
pub const CELL_SIZE: usize = 4096;

pub const FIXED_LEN: usize = 4;
pub const MAC_LEN: usize = 32;
pub const RT_LEN: usize = 48;
pub const ELEM_LEN: usize = 32;
pub const TAG_LEN: usize = 16;
pub const NONCE_LEN: usize = 12;
pub const MLKEM_EK_LEN: usize = 1184;
pub const MLKEM_DK_LEN: usize = 2400;
pub const MLKEM_CT_LEN: usize = 1088;
pub const SLOT1_LEN: usize = MLKEM_CT_LEN + MAC_LEN + RT_LEN; // 1168
pub const SLOTI_LEN: usize = ELEM_LEN + MAC_LEN + RT_LEN; // 112

pub const CMD_FORWARD: u64 = 1 << 0;
pub const CMD_TERMINATE: u64 = 1 << 1;

pub fn header_len(v: usize) -> usize {
    FIXED_LEN + SLOT1_LEN + (v - 1) * SLOTI_LEN
}

pub fn payload_len(v: usize) -> usize {
    CELL_SIZE - header_len(v) - TAG_LEN
}

// ---------------------------------------------------------------------------
// Keys
