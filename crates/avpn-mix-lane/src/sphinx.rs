pub struct BuiltCell {
    pub cell: Vec<u8>,
    pub payload_key: [u8; 32],
    pub hop_secrets: Vec<[u8; 32]>,
}

impl std::fmt::Debug for BuiltCell {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("BuiltCell")
            .field("cell_len", &self.cell.len())
            .finish()
    }
}

fn seal_inner(key: &[u8; 32], nonce: &[u8; 12], message: &[u8], padded_len: usize) -> Vec<u8> {
    let mut inner = vec![0u8; padded_len];
    inner[..2].copy_from_slice(&(message.len() as u16).to_le_bytes());
    inner[2..2 + message.len()].copy_from_slice(message);
    crypto::aead_seal(key, nonce, &[], &inner)
}

fn open_inner(key: &[u8; 32], nonce: &[u8; 12], ct_and_tag: &[u8]) -> Option<Vec<u8>> {
    let inner = crypto::aead_open(key, nonce, &[], ct_and_tag)?;
    if inner.len() < 2 {
        return None;
    }
    let len = u16::from_le_bytes([inner[0], inner[1]]) as usize;
    if 2 + len > inner.len() {
        return None;
    }
    Some(inner[2..2 + len].to_vec())
}

/// Build a full option E cell for `path`, terminating at `dest` (mailbox).
pub fn build_cell(
    path: &[MixKeys],
    dest: &[u8; 16],
    plaintext: &[u8],
    rng: &mut dyn SphinxRng,
) -> Result<BuiltCell, SphinxError> {
    let v = path.len();
    let plen = payload_len(v);
    if plaintext.len() + 2 > plen - NONCE_LEN {
        return Err(SphinxError::PayloadTooLarge);
    }
    let ing = build_header(path, dest, rng)?;
    let pkey = payload_key(&ing.k_secrets);

    let mut nonce = [0u8; NONCE_LEN];
    rng.fill(&mut nonce);
    let sealed = seal_inner(&pkey, &nonce, plaintext, plen - NONCE_LEN);
    let (ct, tag) = sealed.split_at(sealed.len() - TAG_LEN);

    let mut cell = ing.header.clone();
    cell.extend_from_slice(&nonce);
    cell.extend_from_slice(ct);
    cell.extend_from_slice(tag);
    debug_assert_eq!(cell.len(), CELL_SIZE);

    // R3: pre-mask the payload region with every hop's stream; hop i
    // removes PM_i during processing. SURB replies skip this (the replier
    // holds no path secrets); their hops ADD masks and the SURB creator
    // strips them all at open time — same per-hop operation either way.
    let hlen = header_len(v);
    for i in 1..=v {
        let pm = pmask_stream(&ing.k_secrets[i - 1], i, v);
        for (b, m) in cell[hlen..].iter_mut().zip(&pm) {
            *b ^= m;
        }
    }

    Ok(BuiltCell {
        cell,
        payload_key: pkey,
        hop_secrets: ing.k_secrets,
    })
}

/// Open a delivered cell's payload with the payload key (sender/creator,
/// loop cover, or after `recipient_open` unwrapping the key transport).
pub fn open_payload(cell: &[u8], pkey: &[u8; 32]) -> Option<Vec<u8>> {
    let v = parse_fixed(cell).ok()?;
    let hlen = header_len(v);
    let plen = payload_len(v);
    let payload = &cell[hlen..hlen + plen];
    let mut nonce = [0u8; NONCE_LEN];
    nonce.copy_from_slice(&payload[..NONCE_LEN]);
    let ct_and_tag = &cell[hlen + NONCE_LEN..CELL_SIZE];
    open_inner(pkey, &nonce, ct_and_tag)
}

/// Replay tag for the mix's rotating cache (§1.6): SHA-256 over all v MAC
/// fields at ingress. Deterministic per cell; identical for a replay of the
/// same captured bytes; fresh randomness makes distinct cells differ.
pub fn replay_tag(cell: &[u8]) -> Result<[u8; 32], SphinxError> {
    let v = parse_fixed(cell)?;
    let mut buf = Vec::with_capacity(MAC_LEN * v);
    for i in 1..=v {
        let off = mac_field(i);
        buf.extend_from_slice(&cell[off..off + MAC_LEN]);
    }
    Ok(crypto::sha256(&buf))
}

